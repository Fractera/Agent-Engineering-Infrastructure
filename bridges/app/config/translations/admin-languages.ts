// решается. Файл редактирует ВЛАДЕЛЕЦ, по одной строке за раз.
// =============================================================================
//
// ЗАКОН ПРОДУКТА: панель управления и панель регистрации существуют на ВСЕХ 82
// языках — тех же, что у слоя авторизации. Причина не в щедрости, а в воронке:
// мы не знаем, из какой страны придёт покупатель, и узнать не можем до того,
// как он вошёл. Отдать ему панель по-английски, попросить выбрать язык и потом
// переключить — значит потребовать работы раньше, чем он получил ценность.
// Панель обязана открыться на его языке сразу.
//
// ЭТО НЕ ТО ЖЕ, ЧТО ЯЗЫКИ ПУБЛИЧНОГО ПРИЛОЖЕНИЯ. У приложения на :3000 набор
// языков живёт в переменной окружения `NEXT_PUBLIC_SUPPORTED_LANGUAGES`, потому
// что там выбирает владелец: это его сайт и его рынки. Здесь выбора нет и быть
// не может — панель наша, а приходят в неё со всего мира. Никогда не сводить
// эти два механизма в один.
//
// ЗАЧЕМ ТОГДА ЭТОТ ФАЙЛ. Пока панель строится, каждая сборка предрендеривает
// 26 страниц × число языков. На двух языках это 52 страницы и ~16 МБ; на 82 —
// около 2 132 страниц и ~150 МБ, то есть минуты ожидания на КАЖДОЙ итерации
// разработки. Поэтому здесь стоит тормоз периода разработки: список языков,
// которые собираются СЕЙЧАС.
//
// КАК ИМ ПОЛЬЗОВАТЬСЯ. Появился перевод на новый язык — добавить его код в
// массив ниже. Ничего больше: маршруты, меню, переключатель языка в подвале и
// предрендер подхватывают список сами. Когда переводы дойдут до всех 82,
// массив станет полным списком, и тормоз исчезнет сам — снимать его отдельно не
// придётся.
//
// Порядок в массиве = порядок в списке переключателя внутри региона.
// Первый элемент — язык по умолчанию (см. `DEFAULT_ADMIN_LANG`).

import { ALL_LANGUAGE_METADATA } from "./language-metadata";

// Языки, собираемые СЕЙЧАС. Сегодня их два; расти этот список будет вручную, по
// мере поступления переводов, до всех 82.
export const ADMIN_BUILD_LANGUAGES: readonly string[] = ["en", "ru"];

// Полный целевой набор — 82 языка слоя авторизации (ключи `STRINGS` в
// `services/auth/lib/i18n/auth-strings.ts`). Держится здесь, чтобы всегда было
// видно, сколько ещё осталось, и чтобы «сколько всего» не приходилось искать в
// другом сервисе.
export const ADMIN_TARGET_LANGUAGES: readonly string[] = [
  "en", "fr", "es", "pt", "de", "it", "nl", "sv", "no", "da", "fi", "is", "el", "pl", "cs", "sk",
  "hu", "ro", "hr", "sl", "et", "lv", "lt", "mt", "ca", "gl", "cy", "ga", "eu", "ru", "uk", "be",
  "bg", "sr", "bs", "mk", "sq", "kk", "uz", "ky", "tg", "tk", "az", "hy", "ka", "mn", "ar", "tr",
  "he", "fa", "ku", "af", "sw", "ha", "yo", "ig", "am", "zu", "xh", "rw", "so", "zh", "ja", "ko",
  "hi", "ur", "bn", "te", "mr", "kn", "gu", "ml", "ta", "ne", "vi", "th", "id", "ms", "tl", "my",
  "km", "lo",
];

// Опечатка в коде языка не должна порождать маршрут. Пропускаем только то, что
// есть в каталоге языков, — он же даёт флаг и родное название переключателю.
export const ADMIN_LANGUAGES: readonly string[] = ADMIN_BUILD_LANGUAGES.filter(
  (code) => Boolean(ALL_LANGUAGE_METADATA[code]),
);

// Сколько ещё не собирается — чтобы прогресс был виден числом, а не на глаз.
export const ADMIN_LANGUAGES_REMAINING = ADMIN_TARGET_LANGUAGES.filter(
  (code) => !ADMIN_LANGUAGES.includes(code),
).length;
