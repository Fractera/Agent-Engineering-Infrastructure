/** Что известно про страницу: уровень тревоги и записи, её породившие. */
export type SlugAlarm = { level: WarningLevel; ids: AdminWarning["id"][] };

/**
 * Свод предупреждений ПО СТРАНИЦАМ (владелец 2026-08-15).
 *
 * ЗАЧЕМ. Область «Прежде чем начинать» отвечает на вопрос «с чего начать», но
 * она живёт вверху меню и на главной странице её нет вовсе. Человек, который уже
 * прочитал её и пошёл искать раздел глазами, снова не видит, какой из сорока
 * пунктов ему нужен. Поэтому цвет обязан дойти до САМОГО пункта — и в меню, и в
 * дереве страниц на главной.
 *
 * Считается ИЗ ТОГО ЖЕ списка, а не второй проверкой. Пока метка у страницы
 * вычислялась своим условием (в меню так было зашито `doc-use-cases`), два места
 * могли разойтись: область говорила одно, пункт — другое.
 *
 * Красный ПОБЕЖДАЕТ оранжевый: на одну страницу указывают несколько записей
 * (три инструмента разработки ведут в `dev-tools`), и пункт обязан носить цвет
 * самого строгого из них — иначе блокирующее требование спрячется за советом.
 */
export function warningsBySlug(warnings: AdminWarning[]): Map<AdminPageSlug, SlugAlarm> {
  const out = new Map<AdminPageSlug, SlugAlarm>();
  for (const w of warnings) {
    const prev = out.get(w.slug);
    if (!prev) {
      out.set(w.slug, { level: w.level, ids: [w.id] });
      continue;
    }
    prev.ids.push(w.id);
    if (w.level === "blocking") prev.level = "blocking";
  }
  return out;
}

export function collectWarnings(): AdminWarning[] {
  const out: AdminWarning[] = [];

  // 🔒 ПЕРВОЙ — ОТКРЫТАЯ ДВЕРЬ, А НЕ НЕЗАКОНЧЕННАЯ НАСТРОЙКА (шаг 520).
  //
  // Все остальные записи говорят «ты ещё не сделал»; эта — «твой сервер сейчас
  // открыт постороннему». Она обязана стоять выше любой настройки, потому что
  // пока она горит, всё остальное делается на виду у всего интернета.
  if (authBypassLeaking()) {
    out.push({ id: "auth-bypass", level: "blocking", slug: "domain" });
  }

  // Красные — без них разработка не начинается.
  //
  // 🔒 ЯЗЫКИ СТОЯТ ПЕРВЫМИ (владелец 2026-08-13), и порядок здесь содержательный.
  // Набор языков запекается НА СБОРКЕ: он задаёт `generateStaticParams`, включает
  // или выключает одноязычный режим и тем самым решает, будет ли у адресов
  // языковой сегмент. Выбрать его после того, как проект построен, — значит
  // переписать адреса всех страниц разом.
  //
  // Проверяется ОТМЕТКА, а не значение: языки есть всегда (свежий сервер несёт
  // `en`), поэтому «не настроено» по значению не читается. Отметку ставит
  // сохранение на странице языков — и один английский, сохранённый осознанно,
  // закрывает предупреждение так же полно, как двенадцать языков.
  // 🔒 ПРЕДУПРЕЖДЕНИЕ О ЯЗЫКАХ УБРАНО ОТСЮДА 2026-08-29 ВМЕСТЕ С РАЗДЕЛОМ.
  //
  // Языки переехали в сам проект (`/{lang}/architect/app-config?group=multilang`),
  // и раздела панели больше нет. Блокирующее предупреждение, ведущее на страницу,
  // которой в меню не существует, — тупик: человек видит красное, нажимает и не
  // попадает никуда.
  //
  // 🛑 ДОЛГ, НАЗВАННЫЙ ВСЛУХ: сама тревога верна и не отменена. Выбрать языки
  // после того, как проект построен, значит переписать адреса всех страниц разом —
  // и сказать об этом обязан теперь слой архитектора, у себя. Здесь для этого нет
  // ни места, ни адреса.
  //
  // Связь считается настоящей ТОЛЬКО когда её подтвердил сам GitHub: адрес
  // репозитория без отметки проверки — это введённые данные, а не связь, и
  // первая же отправка отказала бы. Ту же черту проводит подвал панели
  // (`/api/config/project-state`), и черта обязана быть одна: пока она стояла
  // в двух местах по-разному, предупреждение горело, а кнопки «Забрать» и
  // «Отправить» выглядели рабочими (владелец 2026-08-13).
  if (!envHas(APP_ENV, "USER_GITHUB_REPO_URL") || !envHas(APP_ENV, "USER_GITHUB_VERIFIED_AT")) {
    out.push({ id: "github", level: "blocking", slug: "project-start" });
  }
  //
  // 🔒 ПЕРЕНОС `.env.local` — ОТДЕЛЬНЫЙ ШАГ, И БЕЗ НЕГО ЛОКАЛЬНАЯ РАБОТА НЕ
  // НАЧИНАЕТСЯ ВОВСЕ (владелец 2026-08-19).
  //
  // Человек подключил GitHub, забрал проект на свою машину — и не запустил
  // ничего: `.gitignore` слота блокирует `.env`, `.env.local` и `.env.*.local`,
  // поэтому ключи через git не едут НИКОГДА, и это сделано намеренно. Забрать их
  // можно ровно одной кнопкой — выгрузкой на странице «Переменные окружения».
  //
  // Об этом шаге не говорилось нигде: ни в письме после развёртывания, ни здесь,
  // ни в подвале. Тупик выглядел как поломка продукта, а поломки не было.
  //
  // Красный, потому что это не совет: без файла локальный клон не поднимается.
  // Стоит СРАЗУ ЗА GitHub — сначала проект попадает на машину, потом к нему
  // приезжают ключи; обратный порядок заставил бы переносить их в пустоту.
  //
  // Гаснет отметкой о поступке, а не фактом скачивания: доехал ли файл до папки
  // проекта, отсюда не видно (`ENV_TRANSFERRED_KEY`, `lib/dev-tools-marks.ts`).
  if (!envHas(APP_ENV, ENV_TRANSFERRED_KEY)) {
    out.push({ id: "env-local", level: "blocking", slug: "env" });
  }
  // 🔒 ЧТО ТРЕБУЕТСЯ, РЕШАЕТ РЕЖИМ РАЗРАБОТКИ (владелец 2026-08-18).
  //
  // Здесь стоял гейт кейсов: пока ни один продукт не имел подтверждённых кейсов,
  // горела красная тревога, и она горела на СВЕЖЕЙ панели — у человека, который
  // ещё не решил, нужны ли ему кейсы вообще. Требование предъявлялось раньше
  // вопроса, и ответить на него было негде.
  //
  // Теперь вопрос задан явно, страницей «Режим разработки», и требование живёт
  // ровно в том режиме, который его порождает. `classic` и `steps` не
  // проектируют продуктов — им не о чем предупреждать, и группа «Продукты» у них
  // спрятана (`hiddenSlugs()`). Тревога, ведущая в спрятанный раздел, читалась
  // бы как поломка панели.
  const features = readFeatures().config;

  // 🔒 РЕЖИМ РАЗРАБОТКИ — ОРАНЖЕВЫЙ, И ОН ЖЕ РЕШАЕТ, ЧТО ПОТРЕБУЮТ ОСТАЛЬНЫЕ
  // (владелец 2026-08-19).
  //
  // Вчерашний шаг заменил гейт кейсов страницей выбора режима, но записи в этом
  // своде не завёл: на свежем сервере пункт «Режим разработки» не был подсвечен
  // ничем, и человек проходил мимо вопроса, от которого зависит весь его порядок
  // работы. Молчание конфига действует как `classic` — то есть выбор как бы
  // сделан за него и молча.
  //
  // Оранжевый, а не красный: `classic` работает и ничего не требует, начинать
  // можно. Но начинать, не зная, что режимов три, — не то же самое, что выбрать
  // классический.
  //
  // Гаснет ОТМЕТКОЙ О ПОСТУПКЕ (`developmentModeChosen`), а не значением: по
  // значению «не выбрано» неотличимо от «выбран классический». Оставить текущий
  // режим — такой же выбор, и страница его записывает.
  if (!developmentModeChosen(features)) {
    out.push({ id: "mode", level: "advised", slug: "development-mode" });
  }

  const casesMode = productsDesignOpen(features);

  // 🔒 ГЕЙТ СЧИТАЕТСЯ ПО ВСЕМ ПРОДУКТАМ, НО НЕ МЕШАЕТ РАБОТЕ ПО ГОТОВОМУ
  // (партия 5). Тревога горит, пока НЕ ОПИСАН НИ ОДИН продукт: начатый второй
  // продукт не имеет права остановить разработку первого — иначе владелец
  // перестанет заводить новые. Продуктов нет вовсе — описывать нечего, и это
  // тоже «не готово».
  //
  // 🔒 МЕРА — ОПИСАНИЕ, А НЕ ПОДТВЕРЖДЁННЫЕ КЕЙСЫ (владелец 2026-08-18).
  // Прежняя мера (`useCasesGate(...).kind === "ready"`) требовала пройти опрос и
  // Quiz, то есть работы на модели и на ключе OpenAI, — и вела в тупик ровно так
  // же, как сама тревога. Описание владелец пишет руками за минуту, и это
  // первое, что вообще можно сделать с продуктом.
  const products = listProducts();
  const productDescribed = products.some((p) => (p.description ?? "").trim() !== "");
  const hasOpenAiKey = envHas(APP_ENV, "OPENAI_API_KEY") || envHas(RAG_ENV, "OPENAI_API_KEY");

  // 🔒 ПРОДУКТЫ ИДУТ ПЕРЕД КЛЮЧОМ OPENAI, И ЭТО ПЕРЕСТАНОВКА (2026-08-18).
  //
  // Раньше ключ стоял впереди, и довод был верным для прежней меры: кейсы
  // рождаются в Quiz, Quiz без ключа не отвечает, значит звать «опишите кейсы»
  // раньше ключа значило вести в тупик. Новая мера — описание продукта, оно
  // пишется руками и ключа не требует вовсе. Тупика больше нет, а первым шагом
  // честно становится то, что делается первым.
  if (casesMode && !productDescribed) {
    // Ведёт туда, где работа, а не туда, где объяснение: документ кейсов остался
    // документом, кнопки живут на `/products`.
    out.push({ id: "products", level: "blocking", slug: "products" });
  }

  // 🔒 КЛЮЧ OPENAI КРАСЕН РОВНО В РЕЖИМЕ КЕЙСОВ (2026-08-18). Опрос и Quiz —
  // единственное в панели, что без ключа не делает НИЧЕГО; они живут только в
  // этом режиме. В остальных ключ по-прежнему нужен векторной памяти и графу, но
  // ничего не блокирует — там он оранжевый совет ниже.
  //
  // Требование не удваивается: обе ветки взаимоисключающие.
  if (casesMode && !hasOpenAiKey) {
    out.push({ id: "openai", level: "blocking", slug: "openai" });
  }

  // Оранжевые — начинать можно, но лучше не.
  //
  // Ключ попадает сюда, ТОЛЬКО когда продукты не проектируются: в режиме кейсов
  // он выше и красный. Условие `casesMode` и есть то, что разводит две ветки и
  // не даёт записи задвоиться.
  if (!casesMode && !hasOpenAiKey) {
    out.push({ id: "openai", level: "advised", slug: "openai" });
  }
  // Пока сервер не в защищённом режиме — предупреждение горит, чем бы ни
  // закончились шаги визарда. Это единственное состояние, о котором запись
  // обязана сообщать: не «домен введён», а «проект на нём работает».
  if (!isSecureMode()) {
    out.push({ id: "domain", level: "advised", slug: "domain" });
  }

  // 🔒 БРАУЗЕР У АГЕНТА — ОРАНЖЕВЫЙ И ПОСЛЕДНИЙ (владелец 2026-08-13).
  //
  // Оранжевый, потому что без него всё строится — просто вслепую: агент
  // рассуждает о причине дефекта вместо того, чтобы открыть страницу. Целый
  // класс поломок (ошибки в консоли, поведение без JS, сервис-воркер, страница
  // после выполнения кода) в исходниках не виден вовсе.
  //
  // 🔒 ПРОВЕРЯЕТСЯ ОТМЕТКА, А НЕ НАЛИЧИЕ. Панель работает на сервере, расширение
  // — в браузере разработчика; канала между ними нет, и «проверить» отсюда
  // физически нечего. Отметку присылает сам агент (`/api/dev-tools/browser`),
  // и она ПЕРЕСТАВЛЯЕТСЯ каждую сессию: нашёл — дата обновилась, не нашёл —
  // строка снята. Поэтому запись гаснет честно и так же честно возвращается,
  // если расширение убрали.
  //
  // Тот же приём, что у языков: отметка о поступке вместо проверки значения,
  // которую сделать невозможно.
  //
  // 🔒 ТРИ ИНСТРУМЕНТА ИДУТ ПО ОЧЕРЕДИ И В ЭТОМ ПОРЯДКЕ (владелец 2026-08-14).
  //
  // Сначала браузер — без него всё строится, просто вслепую. Потом Claude Code —
  // тот, кто пишет код. Последним редактор — то, без чего нельзя. Порядок
  // выбран владельцем сознательно и против интуиции «сначала главное»: человек,
  // которому первым делом велят поставить три программы, не ставит ни одной, а
  // начавший с необязательного расширения доходит до конца.
  //
  // 🔒 ПРОВЕРЯЕТСЯ ОТМЕТКА, А НЕ НАЛИЧИЕ. Панель работает на сервере, инструменты
  // — на машине разработчика; канала между ними нет, и «проверить» отсюда
  // физически нечего. Отметку ставит либо человек галочкой на странице, либо
  // агент своим вызовом. Снял галочку — предупреждение честно вернулось.
  if (!envHas(APP_ENV, markKey("browser"))) {
    out.push({ id: "dev-browser", level: "advised", slug: "dev-tools" });
  }
  if (!envHas(APP_ENV, markKey("claude-code"))) {
    out.push({ id: "dev-claude-code", level: "advised", slug: "dev-tools" });
  }
  if (!envHas(APP_ENV, markKey("editor"))) {
    out.push({ id: "dev-editor", level: "advised", slug: "dev-tools" });
  }


  return out;
}
