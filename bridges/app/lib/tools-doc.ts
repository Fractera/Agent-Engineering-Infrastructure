export type ToolParam = {
  name: string;
  type: string;
  required: boolean;
  /** Что это и почему оно нужно — а не пересказ имени. */
  about: string;
};

export type ToolDoc = {
  /** Одной фразой: зачем инструмент существует. */
  purpose: string;
  /** Как он устроен внутри: что происходит и где. Без этого агент не поймёт границ. */
  mechanics: string[];
  /** Точная строка импорта — с учётом того, именованный экспорт или по умолчанию. */
  importLine: string;
  /** Сигнатура вызова как она есть в коде. */
  signature: string;
  params: ToolParam[];
  /** Что инструмент отдаёт наружу и когда. */
  returns: string;
  /** Рабочий пример — его можно вставить и он соберётся. */
  example: string;
  /** Границы: чего инструмент НЕ делает и что сломается при неверном применении. */
  limits: string[];
};

