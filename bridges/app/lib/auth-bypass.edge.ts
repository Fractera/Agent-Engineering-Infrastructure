// 🔒 ГРУБЫЙ ВАРИАНТ ПРАВИЛА — ТОЛЬКО ДЛЯ `proxy.ts` (шаг 520, 2026-08-20).
//
// Настоящее правило (`auth-bypass.ts`) читает флаг режима из файла окружения:
// копия в памяти процесса умеет устареть и однажды открыла весь контур интернету.
// Но `proxy.ts` исполняется в среде Edge, где `node:fs` не существует, — файловая
// версия туда не соберётся.
//
// ПОЧЕМУ ЭТО НЕ ДЫРА. Прокси решает, пускать ли запрос дальше по маршруту; кто ты —
// решает серверный слой (`lib/service-auth.ts`, `lib/require-auth.ts`), и он берёт
// флаг ИЗ ФАЙЛА. Устаревшее `true` здесь способно лишь довести запрос до места,
// которое само откажет.
//
// 🚫 НЕ ИМПОРТИРОВАТЬ НИГДЕ, КРОМЕ `proxy.ts`.
export function shouldBypassAuthEdge(): boolean {
  return process.env.NODE_ENV === "development"
      || process.env.FRACTERA_IP_NODOMAIN_MODE === "true";
}
