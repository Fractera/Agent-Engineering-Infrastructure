//
// 🔒 ЗАЧЕМ ОТДЕЛЬНОЕ СОСТОЯНИЕ, А НЕ `lib/launch.ts`. Владелец, потеряв введённый
// адрес после перезагрузки, спросил прямо: «почему ты не рисуешь сохранённые
// данные — ты сохраняешь?». Ответ был «нет», и причина была верная: запись в
// `USER_LAUNCH_*` двигает состояние ЖИВОГО мастера, а его трогать запрещено.
//
// Выбор владельца — «replace logic to new flow»: у нового пути СВОИ ключи.
//
// 🪦 СОСЕДСТВО КОНЧИЛОСЬ 2026-08-29: вкладка `/[lang]/github` со старым мастером
// удалена решением владельца, и `USER_FLOW_*` остались единственным состоянием
// пути запуска. Ключи `USER_LAUNCH_*` в `.env.local` уже развёрнутых серверов
// НЕ трогаются и не чистятся: их никто больше не читает, а стирать чужой файл
// ради опрятности — операция с последствиями и без выгоды.
//
// 🔒 ПРЕФИКС СВОЙ И НЕПЕРЕСЕКАЮЩИЙСЯ: `USER_FLOW_`. Ни одного ключа из
// `USER_LAUNCH_*` здесь не читается и не пишется — проверяется зондом, а не
// обещанием.
//
// 🔒 ХРАНИТСЯ ЗНАЧЕНИЕ, А НЕ ФАКТ «ПРОЙДЕНО». Шаг считается пройденным ровно
// тогда, когда у него есть непустое значение: второй ключ «пройдено» рядом со
// значением — это второй источник правды, который через неделю разойдётся с
// первым. Тот же закон, что в `lib/launch.ts`: «состояние выводится из фактов, а
// не хранится отдельно».
//
// ✗ ЧЕМ ОПЛАЧЕНА ЭТА ОСТОРОЖНОСТЬ (шаг 25): отметка одного шага была заимствована
// у другого, и мастер поздравлял человека с тем, чего он не делал. Здесь у
// каждого шага свой ключ, и заимствований нет вовсе.

import { getValue, setValue, clearPrefix } from "@/lib/dev-tools-marks";

/** Префикс всех ключей нового пути. По нему же идёт сброс. */
export const FLOW_PREFIX = "USER_FLOW_";

/**
 * Шаги пути «стартовый шаблон», у которых есть сохраняемое значение.
 *
 * 🔒 СПИСОК ЗДЕСЬ, А НЕ В СТРАНИЦАХ: он нужен и странице шага, и карте пути, и
 * сбросу. Три копии разошлись бы на первой же правке.
 */
export const FLOW_STEPS = [
  "repo-url", "token",
  "donor-url", "adopt-repo-url", "adopt-token",
] as const

// 🔒 `donor-url` ПРИНАДЛЕЖИТ ВТОРОМУ ПУТИ, И КЛЮЧ У НЕГО СВОЙ (35-1, 2026-08-31).
// Второй путь ведёт человека не к пустому репозиторию, а к ЧУЖОМУ проекту: он
// сначала принимает донора и только потом заводит своё. Общий ключ с `repo-url`
// означал бы, что прошедший первый путь видит загоревшиеся шаги второго — то есть
// поздравление с тем, чего он не делал (дефект, оплаченный шагом 25).
//
// 🔒 ПЕРЕЧИСЛЕНИЕ ОДНО НА ОБА ПУТИ, А ПОРЯДОК — У КАЖДОГО СВОЙ. Здесь живут
// ЗНАЧЕНИЯ, а не последовательность; последовательность знает `_steps.ts` своего
// пути. Второе перечисление значений разошлось бы с первым при первой правке.
export type FlowStep = (typeof FLOW_STEPS)[number];

// ── ДВА ПУТИ, ОДНА МЕХАНИКА, РАЗНОЕ СОСТОЯНИЕ (35-6, 2026-08-31) ────────────
//
// 🔒 ПОЧЕМУ У ВТОРОГО ПУТИ СВОИ КЛЮЧИ, А НЕ ОБЩИЕ С ПЕРВЫМ. Вопрос шага звучит
// одинаково — «адрес вашего пустого репозитория» — но смысл разный: у первого
// пути человек отправляет туда СТАРТОВЫЙ ШАБЛОН, у второго — ЧУЖОЙ ПРОЕКТ,
// который стал его. Общий ключ означал бы, что прошедший один путь видит
// загоревшиеся шаги другого, то есть поздравление с тем, чего он не делал.
// ✗ ровно этим оплачен шаг 25.
//
// 🔒 ПОЧЕМУ МЕХАНИКА ОБЩАЯ. Форма поля, вопрос к GitHub, отправка — одно и то
// же; второй экземпляр этого кода разошёлся бы с первым молча. Двери берут
// ПАРУ значений по имени пути, а не хранят её у себя.
//
// 🔒 УМОЛЧАНИЕ — ПЕРВЫЙ ПУТЬ. Он работает и написан раньше; заставить его
// страницы называть себя по имени значило бы тронуть их без нужды. Новое
// приходит с именем, старое молчит и получает прежнее поведение.

export const LAUNCH_PATHS = ["starter", "adopt"] as const;
export type LaunchPath = (typeof LAUNCH_PATHS)[number];

export const isLaunchPath = (v: unknown): v is LaunchPath =>
  typeof v === "string" && (LAUNCH_PATHS as readonly string[]).includes(v);

/** Какие ДВА значения питают проверку связи и отправку у каждого пути. */
export const PATH_INPUTS: Record<LaunchPath, { url: FlowStep; token: FlowStep }> = {
  starter: { url: "repo-url", token: "token" },
  adopt: { url: "adopt-repo-url", token: "adopt-token" },
};

export const isFlowStep = (v: unknown): v is FlowStep =>
  typeof v === "string" && (FLOW_STEPS as readonly string[]).includes(v);

const key = (step: FlowStep): string =>
  `${FLOW_PREFIX}${step.toUpperCase().replace(/-/g, "_")}`;

/** Значение шага. Пустая строка означает «шаг не пройден». */
export function flowValue(step: FlowStep): string {
  return getValue(key(step)).trim();
}

export function setFlowValue(step: FlowStep, value: string | null): void {
  const next = value && value.trim() !== "" ? value.trim() : null;
  const changed = next !== (getValue(key(step)).trim() || null);
  setValue(key(step), next);

  // 🔒 СМЕНИЛОСЬ ПРОВЕРЕННОЕ — ОТМЕТКА ПРОВЕРКИ ГАСНЕТ. GitHub отвечал про ТОТ
  // адрес и ТОТ токен; после замены зелёная отметка утверждала бы то, чего никто
  // не спрашивал. Гасить надо здесь, у единственного писателя значений, — иначе
  // однажды появится второй путь записи, который об этом не знает.
  //
  // ✗ 🔒 НО ТОЛЬКО СВОИМИ ЗНАЧЕНИЯМИ (найдено чтением кода в 35-3, 2026-08-31).
  // Строка была написана в 28-17, когда значений было два и оба принадлежали
  // ПЕРВОМУ пути. В 35-1 к ним добавился `donor-url` второго пути — и сохранение
  // адреса донора стало гасить проверку связи ЧУЖОГО пути: человек, прошедший
  // первый путь, терял зелёную отметку оттого, что заглянул во второй. Это ровно
  // тот дефект, которым оплачен шаг 25, только повёрнутый другой стороной: там
  // отметка загоралась незаслуженно, здесь — гасла незаслуженно.
  // Гаснет проверка ТОГО пути, чьё значение сменилось, и только его.
  if (changed) {
    for (const path of LAUNCH_PATHS) {
      const { url, token } = PATH_INPUTS[path];
      if (step === url || step === token) setValue(verifiedKey(path), null);
    }
  }
}

/** Пройден ли шаг. Один источник правды — наличие значения. */
export function flowDone(step: FlowStep): boolean {
  return flowValue(step) !== "";
}

/**
 * Значение, показываемое человеку.
 *
 * 🔒 СЕКРЕТ НАРУЖУ НЕ ОТДАЁТСЯ ЦЕЛИКОМ. Токен сохранён — человеку нужно видеть,
 * ЧТО он сохранён, а не сам токен: страница панели открывается при коллегах, на
 * проекторе и в записи экрана. Показываются четыре последних знака, остальное —
 * точки. Адрес репозитория секретом не является и показывается целиком.
 */
export function flowShown(step: FlowStep): string {
  const v = flowValue(step);
  // 🔒 СЕКРЕТ ОПОЗНАЁТСЯ ПО РОЛИ, А НЕ ПО ОДНОМУ ИМЕНИ (35-6). Здесь стояло
  // `step !== "token"`, и это работало, пока токен был один. С появлением
  // `adopt-token` такая проверка показала бы второй токен целиком — на экране,
  // который открывают при коллегах и в записи экрана. Роль берётся у
  // `PATH_INPUTS`, то есть там же, где заведена пара значений.
  const isSecret = LAUNCH_PATHS.some((p) => PATH_INPUTS[p].token === step);
  if (v === "" || !isSecret) return v;
  return `••••••••${v.slice(-4)}`;
}

/** Сброс всего состояния нового пути. Живого мастера НЕ касается. */
export function resetFlow(): string[] {
  return clearPrefix(FLOW_PREFIX);
}

/** Сколько шагов пути пройдено — для карты пути и шкалы. */
export function flowDoneCount(): number {
  return FLOW_STEPS.filter(flowDone).length;
}

// ── ШАГ 3: ПРОВЕРКА СВЯЗИ ───────────────────────────────────────────────────
//
// 🔒 ЭТО ОТМЕТКА, А НЕ ЗНАЧЕНИЕ, И ПОТОМУ ЖИВЁТ ОТДЕЛЬНО. У шагов 1 и 2 факт
// «пройден» выводится из наличия значения; у проверки значения нет — есть только
// ответ GitHub и время, когда он пришёл. Втиснуть её в `FLOW_STEPS` значило бы
// назвать временну́ю метку «значением шага» и однажды показать её человеку в
// поле ввода.
//
// 🔒 ОТМЕТКА ГАСНЕТ ПРИ ЛЮБОЙ СМЕНЕ АДРЕСА ИЛИ ТОКЕНА. Проверено было ТО, что
// стояло в тот момент; заменил токен — проверка больше ничего не утверждает.
// Оставить зелёным — ровно тот дефект шага 25, где мастер поздравлял человека с
// тем, чего он не делал.

export const FLOW_VERIFIED_KEY = `${FLOW_PREFIX}VERIFIED_AT`;

/**
 * Ключ отметки проверки для пути.
 *
 * 🔒 У ПЕРВОГО ПУТИ ИМЯ ОСТАЛОСЬ ПРЕЖНИМ, и это не небрежность. На развёрнутых
 * серверах в `.env.local` уже лежит `USER_FLOW_VERIFIED_AT`; переименовать его
 * значило бы погасить проверку у всех, кто её прошёл, — молча и без причины.
 */
const verifiedKey = (path: LaunchPath): string =>
  path === "starter" ? FLOW_VERIFIED_KEY : `${FLOW_PREFIX}ADOPT_VERIFIED_AT`;

// 🪦 `VERIFIED_INPUTS` УДАЛЁН 35-6: список «что питает проверку» переехал в
// `PATH_INPUTS`, где он живёт вместе с самой парой значений. Две таблицы об
// одном разошлись бы на третьем пути.

export function flowVerifiedAt(path: LaunchPath = "starter"): string {
  return getValue(verifiedKey(path)).trim();
}

export function flowVerified(path: LaunchPath = "starter"): boolean {
  return flowVerifiedAt(path) !== "";
}

export function setFlowVerified(on: boolean, path: LaunchPath = "starter"): void {
  setValue(verifiedKey(path), on ? new Date().toISOString() : null);
}

// ── ШАГ 4: ОТПРАВКА ПРОЕКТА ─────────────────────────────────────────────────
//
// 🔒 ОТМЕТКА ОТПРАВКИ НЕ ГАСНЕТ ПРИ СМЕНЕ ТОКЕНА — и это отличие от проверки
// осознанное. Проверка утверждает про НЫНЕШНИЕ данные: сменил токен — она больше
// ничего не утверждает. Отправка утверждает про ПРОШЛОЕ СОБЫТИЕ: файлы уехали, и
// новый токен этого не отменяет. Погасить её значило бы соврать в другую сторону.

export const FLOW_PUSHED_KEY = `${FLOW_PREFIX}PUSHED_AT`;

/** Имя первого пути сохранено по той же причине, что и у проверки. */
const pushedKey = (path: LaunchPath): string =>
  path === "starter" ? FLOW_PUSHED_KEY : `${FLOW_PREFIX}ADOPT_PUSHED_AT`;

export function flowPushedAt(path: LaunchPath = "starter"): string {
  return getValue(pushedKey(path)).trim();
}

export function flowPushed(path: LaunchPath = "starter"): boolean {
  return flowPushedAt(path) !== "";
}

export function setFlowPushed(on: boolean, path: LaunchPath = "starter"): void {
  setValue(pushedKey(path), on ? new Date().toISOString() : null);
}

// ── ВТОРОЙ ПУТЬ, ШАГ 2: ДОНОР ПОДКЛЮЧЁН ─────────────────────────────────────
//
// 🔒 ЭТО СОБЫТИЕ, А НЕ ЗНАЧЕНИЕ, И ПОТОМУ ОТМЕТКА, А НЕ `FLOW_STEPS`. У шага 1
// второго пути есть значение — адрес донора. У шага 2 значения нет: есть факт,
// случившийся на сервере, — содержимое слота заменено и отвязано, и сборка на
// нём прошла. Тот же род, что `PUSHED_AT`, и та же причина отдельной жизни.
//
// 🔒 НЕ ГАСНЕТ ПРИ СМЕНЕ АДРЕСА ДОНОРА — по тому же правилу, что отметка
// отправки. Она утверждает про ПРОШЛОЕ СОБЫТИЕ: файлы заменены, и новый адрес в
// поле этого не отменяет. Погасить её значило бы соврать в другую сторону — и
// предложить человеку заменить слот повторно, когда он этого не просил.
//
// 🔒 СТАВИТ ЕЁ МАШИНА, А НЕ ЧЕЛОВЕК, и дверь обязана спросить правду сама.
// Человек не может закрыть этот шаг из вежливости: у панели есть глаза на
// собственный слот — и, значит, отговорки «спросить неоткуда» здесь нет.

export const FLOW_ADOPTED_KEY = `${FLOW_PREFIX}ADOPTED_AT`;

export function flowAdoptedAt(): string {
  return getValue(FLOW_ADOPTED_KEY).trim();
}

export function flowAdopted(): boolean {
  return flowAdoptedAt() !== "";
}

export function setFlowAdopted(on: boolean): void {
  setValue(FLOW_ADOPTED_KEY, on ? new Date().toISOString() : null);
}

