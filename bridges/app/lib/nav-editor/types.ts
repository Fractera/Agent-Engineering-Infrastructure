// Контракт данных раздела «Верхнее меню».
//
// Форма повторяет то, что читает гостевое приложение
// (`fractera-next-starter/lib/menu/nav-config.ts`), — намеренно дословно: две
// формы одного и того же расходятся молча, и расхождение обнаруживается на
// живом сайте, а не здесь.

/** Пункт второго уровня — только внутри группы, дальше вложенности нет. */
export type NavChild = {
  id: string;
  /** Путь БЕЗ языка: `/products`. Язык подставляет приложение. */
  href: string;
  order: number;
  /** Базовая подпись; переводы живут в `i18n["nav.top.<id>.label"]`. */
  label: string;
};

export type NavItem = {
  id: string;
  /** У виртуальной группы адреса нет — она ведёт на первого ребёнка. */
  href?: string;
  order: number;
  label: string;
  children?: NavChild[];
};

/**
 * Слот меню. Их два, и оба собирает владелец: верхняя полоса и подвал.
 * Совпадает с `NavSlot` приложения (`lib/menu/nav-config.ts`) — сознательно
 * дословно: два имени одного и того же разошлись бы молча.
 */
export type NavSlot = "top" | "footer";

export type NavState = {
  /** Пункты ЭТОГО слота. Имя нейтральное: состояние читается и для подвала. */
  items: NavItem[];
  /** Сторона ящика аккаунта — общая настройка, живёт рядом с обоими слотами. */
  authSide: "left" | "right";
};

/** Публичный маршрут приложения — кандидат в кнопки меню. */
export type RouteCandidate = {
  /** Путь без языка: `/products`, `/blog/sample-1`. */
  href: string;
  /** Что показать человеку в списке кандидатов. */
  title: string;
};

/**
 * Узел дерева публичных маршрутов — карта сайта так, как её видит посетитель.
 *
 * `href` пуст у папки, у которой нет своей страницы: перейти по ней нельзя, но
 * внутри могут лежать те, по которым можно. Такой узел раскрывается, но кнопки
 * «добавить» не имеет — предлагать пункт меню, ведущий в никуда, нельзя.
 */
export type RouteNode = {
  /** Имя сегмента: `blog`. Показывается, когда у страницы нет заголовка. */
  segment: string;
  href: string | null;
  title: string;
  children: RouteNode[];
};
