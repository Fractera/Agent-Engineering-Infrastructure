// своё (решение владельца 2026-08-15, каталог переработан целиком 2026-08-16).
//
// 🔒 ЗАЧЕМ ЭТО ПОЯВИЛОСЬ. Вводных вопросов было семь, и они задавались одинаково
// интернет-магазину, клинике и мозгу компании. Экран правки вопросов (2026-08-14)
// снял половину беды: владелец мог переписать чужой вопрос. Но переписывать —
// работа, которую мы перекладывали на человека, ещё не получившего ценности, и
// делал он её вслепую: чтобы понять, ЧТО спросить про маркетплейс, надо уже знать,
// чем маркетплейс отличается от магазина.
//
// Теперь порядок обратный: сначала владелец называет структуру проекта, и только
// потом видит вопросы, написанные ИМЕННО под неё.
//
// 🔒 ВОПРОСОВ БОЛЬШЕ НЕ СЕМЬ, И ЧИСЛО У КАЖДОГО НАПРАВЛЕНИЯ СВОЁ (2026-08-16).
// Владелец продиктовал их по каждой теме двумя независимыми наборами; свод —
// от 12 у портфолио до 30 у трёх самых сложных. Предел тридцать: список, который
// не дочитывают, хуже короткого. Единственное направление с ПУСТЫМ списком —
// `custom`, и это его смысл, а не упущение.
//
// 🔒 ВОПРОСЫ НЕ ПЕРЕИСПОЛЬЗУЮТСЯ МЕЖДУ ТИПАМИ — НИ ОДИН. Это не стилистическое
// требование, а следствие устройства: вопрос «сколько шагов в оформлении заказа»
// бессмыслен для мозга компании, а «что считаем одним конкурентом» — для
// посадочной страницы. Общий вопрос дал бы общий ответ, общий ответ — общий кейс,
// и выбор структуры перестал бы что-либо решать. Ровно эту беду он и лечит.
//
// 🔒 ЗДЕСЬ ТОЛЬКО МАШИННЫЕ ДАННЫЕ. Слова — определение, примеры, признаки и сами
// вопросы — живут в словаре панели под тем же идентификатором, как у страниц
// (`AdminStrings.projectTypes`). Тип объявлен в `admin-strings.ts`, поэтому новый
// вид проекта без слов не соберётся. Идентификаторы машинные и НЕ переводятся
// (правило 4г): по ним лежит выбор в папке проекта.
//
// 🔒 ПОРЯДОК В МАССИВЕ = ПОРЯДОК КНОПОК, И ОН ПО СЛОЖНОСТИ (владелец 2026-08-16).
// Простое сверху, тяжёлое внизу, «своё направление» — всегда последнее. Прежний
// порядок был по частоте прихода; он перестал работать, когда направлений стало
// двадцать одно: человек не сравнивает двадцать карточек по популярности, он
// ищет своё по масштабу задачи.
//
// «Сложность» здесь — не число вопросов, а сколько РАЗНОРОДНЫХ подсистем обязано
// сойтись, чтобы продукт заработал. Одна страница с формой — один механизм.
// Маркетплейс — двое незнакомцев, деньги между ними и разбор споров. «Мозг
// компании» — весь код или вся переписка компании плюс поиск по смыслу плюс
// права доступа.

