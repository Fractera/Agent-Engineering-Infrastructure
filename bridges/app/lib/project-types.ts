//
// ПОРЯДОК В МАССИВЕ = ПОРЯДОК КНОПОК. Он не алфавитный и не случайный: сначала
// четыре направления, с которых люди приходят чаще всего, затем шесть остальных
// массовых, и последними два наших собственных — они самые сильные, но их ещё
