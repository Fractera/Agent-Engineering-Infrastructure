import { readEnvFile } from "@/lib/env-file";

// ЗАЩИЩЁННЫЙ РЕЖИМ — ОДИН ОТВЕТ НА ВЕСЬ ПРОЕКТ.
//
// 🔒 ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ (2026-08-16, разбор по вопросу владельца).
// Вопрос «работает ли проект на своём домене» задавали ДВА места и получали
// РАЗНЫЕ ответы:
//
//   • визард домена спрашивал окружение (`FRACTERA_IP_NODOMAIN_MODE`) — и
//     отвечал верно: шаг 4 не нажат, режим «IP, обычный HTTP»;
//   • предупреждения панели спрашивали базу (`site_settings.domain_status`) —
//     и отвечали «домен активен», потому что это поле становится `active`, когда
//     ВЫПУЩЕН СЕРТИФИКАТ (шаг 2), задолго до перехода в защищённый режим.
//
// Итог был хуже, чем отсутствие проверки: владелец сидел в открытом режиме с
// обойдённой авторизацией, а панель молчала — предупреждение погасло на шаге 2 и
// уже не зажигалось. Предупреждение, гаснущее раньше времени, опаснее
// отсутствующего: первое создаёт уверенность, второе хотя бы её не создаёт.
//
// 🔒 ПОЧЕМУ ИСТИНА ИМЕННО В ОКРУЖЕНИИ. Флаг читает `shouldBypassAuth()`, то есть
// он и есть то, что решает, спрашивают ли у посетителя вход. База описывает
// НАМЕРЕНИЕ («домен заведён, сертификат выпущен»), окружение — ФАКТ («так
// работает сервер прямо сейчас»). Предупреждение обязано говорить о факте.

/**
 * Четыре файла окружения, и требуется согласие ВСЕХ.
 *
 * 🔒 ЛЮБОЙ ОДИН, оставшийся `true` или незаданным, означает открытый режим:
 * достаточно одной службы с обойдённой авторизацией, чтобы защита не работала.
 * Поэтому проверка пессимистична по построению — «защищено» говорится только
 * когда защищено везде.
 */
export const SECURE_MODE_ENV_FILES = [
  "/opt/fractera/services/auth/.env.local",
  "/opt/fractera/bridges/app/.env.local",
  "/opt/fractera/app/.env.local",
  "/opt/fractera/services/data/.env",
];

/**
 * Работает ли сервер в защищённом режиме ПРЯМО СЕЙЧАС.
 *
 * Синхронна и терпит отказ: её зовут предупреждения, которые рисует шапка на
 * каждой странице панели, а упавшая проверка не имеет права уронить панель.
 * Нечитаемый файл трактуется как «не защищено» — честнее промолчать о
 * готовности, чем соврать о ней.
 */
export function isSecureMode(): boolean {
  for (const file of SECURE_MODE_ENV_FILES) {
    try {
      if (readEnvFile(file).FRACTERA_IP_NODOMAIN_MODE !== "false") return false;
    } catch {
      return false;
    }
  }
  return true;
}
