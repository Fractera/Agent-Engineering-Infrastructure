import { modeFlagForChildProcess } from "@/lib/auth-bypass";

// Как панель перезапускает СОСЕДНИЕ службы (найдено живьём 2026-08-19).
//
// 🔒 ПОРТ НАЗЫВАЕТСЯ ЯВНО, ИНАЧЕ СЛУЖБА ЗАБИРАЕТ ПОРТ ПАНЕЛИ. `--update-env`
// заставляет pm2 взять окружение ТОГО, КТО ЗОВЁТ, а зовёт процесс панели, и в
// его окружении `PORT=3002`. Служба данных читает `process.env.PORT ?? 3300`
// (`services/data/server.js:18`) — то есть после такого перезапуска она пыталась
// слушать 3002, получала `EADDRINUSE` и уходила в вечный рестарт.
//
// Что это стоило на живом сервере: **3711 рестартов**, `uptime` ноль, слой данных
// мёртв (на 3300 никто не слушает) — и `pm2 list` всё это время писал `online`.
// Отказ невидим ровно потому, что молчит именно тот слой, через который панель
// узнаёт о состоянии. Служба авторизации уцелела случайно: её `npm run start`
// передаёт `-p 3001` аргументом, и он сильнее переменной.
//
// 🔒 ПОЧЕМУ НЕ `env -u PORT`. Снять переменную мало: pm2 хранит окружение процесса
// и при `--update-env` ДОПОЛНЯЕТ его, а не заменяет, — однажды записанный `3002`
// пережил бы такой перезапуск. Проверено на сервере: помогло только явное
// значение. Поэтому здесь именно `PORT=<свой>`, и он же лечит уже испорченный
// процесс.
//
// `--update-env` при этом остаётся обязательным и по прежней причине: `dotenv`
// читает файл один раз при старте, и без флага служба продолжает жить со старым
// значением флага безопасности в памяти.
// 🔒 ФЛАГ РЕЖИМА НАЗЫВАЕТСЯ ЯВНО — ПО ТОЙ ЖЕ ПРИЧИНЕ, ЧТО И ПОРТ (шаг 520, 2026-08-20).
//
// ЧТО ЭТА КОМАНДА ДЕЛАЛА РАНЬШЕ. `--update-env` берёт окружение ТОГО, КТО ЗОВЁТ, —
// а зовёт процесс панели через `spawn`. В её `process.env` Next при старте оставил
// прежнее значение `FRACTERA_IP_NODOMAIN_MODE`, и перезапуск записывал это прежнее
// значение в обе службы. То есть лечение само разносило заразу: после переключения
// в защищённый режим `fractera-auth` и `fractera-data` продолжали жить с `true` —
// с ПОЛНЫМ ОБХОДОМ АВТОРИЗАЦИИ, открытым интернету, при зелёной панели и правильном
// файле на диске. Проверено на живом сервере 2026-08-20: `auth /api/session` без
// единой куки отдавал `demo@local` с ролью `architect`, `data /db/tables` — таблицы.
//
// Значение берётся ИЗ ФАЙЛА и заново, мимо кэша (`modeFlagForChildProcess`), потому
// что зовут эту команду через доли секунды после того, как файл переписан.
//
// Функция, а не константа: значение вычисляется в момент вызова. Константа здесь
// означала бы снимок, сделанный при загрузке модуля, — ровно тот класс ошибки,
// который мы и лечим.
export function restartAuthAndData(): string {
  const mode = modeFlagForChildProcess();
  return (
    `FRACTERA_IP_NODOMAIN_MODE=${mode} PORT=3300 pm2 restart fractera-data --update-env; ` +
    `FRACTERA_IP_NODOMAIN_MODE=${mode} PORT=3001 pm2 restart fractera-auth --update-env`
  );
}
