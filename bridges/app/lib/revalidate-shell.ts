// Конфиги читаются приложением в рантайме, но публичные страницы статические с
// ISR. Значит записи в файл МАЛО: страница продолжает отдавать прежний HTML,
// пока не истечёт окно перегенерации — до десяти минут. Для человека это
// неотличимо от «переключатель не работает»: он щёлкнул, посмотрел, ничего не
// изменилось и сделал вывод, что продукт сломан.
//
// Замер, ради которого стоит помнить эту функцию: панель записала `auth: false`
// в 19:20, в 19:23 страница по-прежнему отдавала две ссылки `/login`, и только
// позже — ноль. Выключатель работал всё это время.
//
// 🔒 ПОЧЕМУ ОБЩИЙ ФАЙЛ, А НЕ КОПИЯ В КАЖДОМ МАРШРУТЕ. Копий было три (`site`,
// `nav`, `design`) — и ровно поэтому четвёртый маршрут, «Возможности приложения»,
// про сброс просто забыли. Аудит 2026-08-20: сброс звали 3 маршрута конфигов из
// 22. Приём, живущий копиями, не переживает появления нового места вызова.
//
// Работает по принципу «лучшее усилие»: отказ сброса НЕ имеет права уронить
// сохранение. Владелец нажал «сохранить» — значит значение обязано лечь на диск,
// даже если приложение в эту секунду перезапускается.
export function revalidateShell(identity: string): void {
  const url = process.env.SHELL_REVALIDATE_URL ?? "http://127.0.0.1:3000/api/revalidate";
  const headers: Record<string, string> = {
    "Content-Type": "application/json",
    "x-agent-identity": identity,
  };
  const sec = process.env.REVALIDATE_SECRET;
  if (sec) headers.Authorization = `Bearer ${sec}`;
  try {
    void fetch(url, { method: "POST", headers, body: "{}" }).catch(() => {});
  } catch {
    /* сброс — вежливость, а не условие сохранения */
  }
}
