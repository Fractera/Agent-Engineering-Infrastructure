// Режим разработки — общие значения для сервера и браузера.
//
// 🔒 ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ КОНСТАНТА В ОСТРОВКЕ (дефект найден владельцем
// 2026-08-18: белый экран на `/ru/development-mode`).
//
// Список режимов жил в `mode-picker.client.tsx`, и серверная страница
// импортировала его оттуда. Next заменяет экспорты клиентского модуля
// КЛИЕНТСКИМИ ССЫЛКАМИ, поэтому на сервере `MODES` перестаёт быть массивом:
// `MODES.includes(...)` падает с `is not a function`, а страница отдаёт пустой
// экран. В логе это видно, в браузере — нет: страница просто белая.
//
// Правило общее: значение, нужное обеим сторонам, живёт в нейтральном файле.
// Островок берёт его отсюда же — тогда двух списков режимов не существует.

// Порядок в списке — порядок на странице, и он смысловой: от «ничего не
// требую» к «требую больше всего». `migration` стоит последним не по возрасту, а
// потому что это единственный режим, у которого есть внешний источник — чужой
// проект: без него он не начинается вовсе (шаг 533).
export const MODES = ["classic", "steps", "cases", "migration"] as const;
export type DevelopmentMode = (typeof MODES)[number];

export function isDevelopmentMode(v: unknown): v is DevelopmentMode {
  return typeof v === "string" && (MODES as readonly string[]).includes(v);
}

/**
 * Режим проекта из конфига платформы.
 *
 * 🔒 УМОЛЧАНИЕ — `steps` (владелец 2026-08-29, ОТМЕНЯЕТ прежнее `classic`).
 * Дословно: «правильный вариант по дефолту это шаги разработки». Правило
 * действует на КАЖДОЕ новое развёртывание: посевной `PLATFORM-CONFIG` пуст, и
 * режим родившегося сервера берётся отсюда — другого источника у него нет.
 *
 * 🪦 ОТМЕНЕНО 2026-08-29, стояло с 2026-08-18: `classic` — «ничего не требует:
 * спросил — сделали». До него стояло `cases`, отменённое тем же доводом: режим
 * кейсов ТРЕБУЕТ работы — описать продукт, пройти опрос, подтвердить кейсы — и
 * требовал её раньше, чем владелец решил, нужны ли ему кейсы вообще. Обе записи
 * оставлены надгробием: иначе следующая сессия воскресит `classic` по памяти.
 *
 * `steps` цену `cases` НЕ наследует: он не требует ни продукта, ни опроса —
 * только чтобы работа велась шагом. Группа «Продукты» и тревога о неописанном
 * продукте по-прежнему принадлежат одному лишь `cases` (`productsDesignOpen()`).
 */
export function developmentModeOf(config: Record<string, unknown>): DevelopmentMode {
  return isDevelopmentMode(config.developmentMode) ? config.developmentMode : "steps";
}

/**
 * Режим ВЫБРАН осознанно? Это не то же самое, что «какой режим действует».
 *
 * 🔒 РАЗНИЦА СОДЕРЖАТЕЛЬНАЯ (владелец 2026-08-19). Действующий режим есть всегда:
 * молчание конфига читается как `steps`. Поэтому по значению «не выбрано»
 * неотличимо от «выбран режим по умолчанию», и предупреждение по значению не построить
 * — оно либо не загорится никогда, либо не погаснет никогда.
 *
 * Спрашивается ФАКТ ЗАПИСИ: ключ появляется в `PLATFORM-CONFIG` ровно тогда,
 * когда человек нажал кнопку на странице «Режим разработки». Оставить текущий
 * режим — такой же осознанный выбор, как сменить его, и он тоже гасит запись:
 * страница сохраняет значение, даже когда оно совпало с действующим.
 *
 * Тот же приём, что у языков (`USER_LANGUAGES_CONFIRMED_AT`): отметка о поступке
 * вместо проверки значения, которую сделать невозможно.
 */
export function developmentModeChosen(config: Record<string, unknown>): boolean {
  return isDevelopmentMode(config.developmentMode);
}

/**
 * Перенос чужого проекта — действующий режим? Спрашивается там, где поведение
 * агента и поверхность панели зависят от переезда: очередь шагов рождается из
 * разбора чужого кода, а не из кейсов и не из просьбы.
 */
export function migrationOpen(config: Record<string, unknown>): boolean {
  return developmentModeOf(config) === "migration";
}

/**
 * Проектирование продуктов открыто? Это ЕДИНСТВЕННЫЙ вопрос, которым режим
 * влияет на панель, и задаётся он одной функцией: видимость группы «Продукты»,
 * тревога о неописанном продукте и кнопки в карточке режима обязаны отвечать
 * одинаково. Три сравнения со строкой `"cases"` в трёх файлах разошлись бы при
 * первом же добавлении режима.
 */
export function productsDesignOpen(config: Record<string, unknown>): boolean {
  return developmentModeOf(config) === "cases";
}
