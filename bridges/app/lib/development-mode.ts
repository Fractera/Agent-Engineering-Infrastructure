// Режим разработки — общие значения для сервера и браузера.
//
// 🔒 ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ КОНСТАНТА В ОСТРОВКЕ (дефект найден владельцем
// 2026-08-18: белый экран на `/ru/development-mode`).
//
// Список режимов жил в `mode-picker.client.tsx`, и серверная страница
// импортировала его оттуда. Next заменяет экспорты клиентского модуля
// КЛИЕНТСКИМИ ССЫЛКАМИ, поэтому на сервере `MODES` перестаёт быть массивом:
// `MODES.includes(...)` падает с `is not a function`, а страница отдаёт пустой
// экран. В логе это видно, в браузере — нет: страница просто белая.
//
// Правило общее: значение, нужное обеим сторонам, живёт в нейтральном файле.
// Островок берёт его отсюда же — тогда двух списков режимов не существует.

export const MODES = ["classic", "steps", "cases"] as const;
export type DevelopmentMode = (typeof MODES)[number];

export function isDevelopmentMode(v: unknown): v is DevelopmentMode {
  return typeof v === "string" && (MODES as readonly string[]).includes(v);
}

/**
 * Режим проекта из конфига платформы.
 *
 * 🔒 УМОЛЧАНИЕ — `classic` (владелец 2026-08-18, ОТМЕНЯЕТ прежнее `cases`).
 *
 * Здесь стояло `cases` с доводом «умолчанием стоит то, ради чего платформа
 * существует». Довод оказался ценой для человека: режим кейсов ТРЕБУЕТ работы —
 * описать продукт, пройти опрос, подтвердить кейсы, — и требовал её раньше, чем
 * владелец решил, нужны ли ему кейсы вообще. Свежая панель встречала его красной
 * тревогой за то, чего он не выбирал.
 *
 * `classic` ничего не требует: спросил — сделали. Кейсы и шаги владелец включает
 * сам, и вместе с режимом появляется вся их поверхность — группа «Продукты» в
 * меню и тревога о неописанном продукте (`hiddenSlugs()`, `collectWarnings()`).
 */
export function developmentModeOf(config: Record<string, unknown>): DevelopmentMode {
  return isDevelopmentMode(config.developmentMode) ? config.developmentMode : "classic";
}

/**
 * Проектирование продуктов открыто? Это ЕДИНСТВЕННЫЙ вопрос, которым режим
 * влияет на панель, и задаётся он одной функцией: видимость группы «Продукты»,
 * тревога о неописанном продукте и кнопки в карточке режима обязаны отвечать
 * одинаково. Три сравнения со строкой `"cases"` в трёх файлах разошлись бы при
 * первом же добавлении режима.
 */
export function productsDesignOpen(config: Record<string, unknown>): boolean {
  return developmentModeOf(config) === "cases";
}
