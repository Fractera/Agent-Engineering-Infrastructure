// затирать выбор, сделанный на этой.
/**
 * Возможности, которыми управляет СПИСОК на странице «Возможности приложения».
 *
 * Тип назван отдельно, а не выражен через `FeatureKey`, чтобы дисциплина словаря
 * пережила переезд: словарь списка требует строку для каждого ключа ЭТОГО типа,
 * поэтому добавить пункт и забыть перевод по-прежнему нельзя, а `offlineCache`
 * не требует строк там, где его больше не показывают.
 */
export type EditableFeatureKey = Exclude<FeatureKey, "offlineCache">;

