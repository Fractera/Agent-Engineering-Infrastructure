"use client";

// С каким продуктом работает открытая страница (партия 5).
//
// 🔒 ИСТОЧНИК ОДИН — АДРЕС. Страница выбирает продукт по `?product=p2`, и
// островки берут его оттуда же, а не получают пропсом через четыре уровня. Это
// не экономия строк: пропс, забытый в одном компоненте, отправил бы правку в
// другой продукт, и заметил бы это владелец не сегодня, а когда сломался бы
// соседний продукт. У адреса такой ошибки быть не может — он один на страницу.
//
// Пусто означает «первый продукт»: сервер разбирает это сам (`activeProduct`), и
// решать это дважды, в двух местах по-разному, нельзя.

export function productParam(): string | undefined {
  if (typeof window === "undefined") return undefined;
  return new URLSearchParams(window.location.search).get("product") ?? undefined;
}
