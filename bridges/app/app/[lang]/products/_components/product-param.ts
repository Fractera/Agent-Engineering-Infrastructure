"use client";

// С каким продуктом работает открытая страница.
//
// 🔒 ИСТОЧНИК ОДИН — АДРЕС, и с 2026-08-18 это ПУТЬ, а не строка запроса.
// Раньше страница кейсов была одна (`doc-use-cases?product=p2`); теперь у
// каждого продукта свой адрес `/{lang}/products/{id}/…`, и продукт читается
// оттуда. Смысл прежний: островок берёт продукт из адреса, а не получает пропсом
// через четыре уровня — пропс, забытый в одном компоненте, отправил бы правку в
// другой продукт, и заметил бы это владелец не сегодня, а когда сломался бы
// соседний продукт.
//
// Пусто означает «продукт в адресе не назван» — так бывает только на списке
// продуктов, где ни один островок этой функции не зовёт.

export function productParam(): string | undefined {
  if (typeof window === "undefined") return undefined;
  const m = window.location.pathname.match(/\/products\/([^/?#]+)/);
  const id = m?.[1];
  // `use-cases` и прочие вкладки продукта сюда не попадают: они идут ПОСЛЕ
  // идентификатора. Но защита от обратного порядка стоит дёшево.
  return id && id !== "use-cases" ? decodeURIComponent(id) : undefined;
}
