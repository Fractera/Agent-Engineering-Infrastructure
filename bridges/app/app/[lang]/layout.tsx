// Каркас нового слоя панели (шаг 501, фаза Ф1).
//
// ЧТО ЭТО. Второе дерево маршрутов, живущее РЯДОМ со старой панелью на том же
// порту :3002. `/` по-прежнему отдаёт сегодняшнюю оболочку байт в байт;
// `/en/<раздел>` — новую страницу. Пересечения нет: статический сегмент `api`
// в Next имеет приоритет над динамическим `[lang]`, поэтому 58 маршрутов API
// этот layout не перехватывает.
//
// ПОЧЕМУ ЗДЕСЬ НЕТ НИ ОДНОГО КЛИЕНТСКОГО КОМПОНЕНТА. Ради этого весь шаг:
// слова 82 языков остаются на сервере, страница приезжает готовым HTML и
// работает с выключенным JS. Гамбургер сделан на `<details>` — родная
// раскрывашка браузера, ей JS не нужен.
//
// ДОЛГ НА ВРЕМЯ СТРОЙКИ. `<html lang>` задаётся корневым `app/layout.tsx` и
// равен "en" для всех языков: владеть `<html>` может только один корневой
// layout, а он сейчас общий со старой панелью. На переключении (фаза Ф3) этот
// файл станет корневым и получит честный `<html lang={lang}>`.

import type { ReactNode } from "react";
import { notFound } from "next/navigation";
import { getAdminStrings, isAdminLanguage, adminLanguages } from "@/lib/i18n/admin-strings";
import { AdminHeader } from "./_components/admin-header";
import { AdminFooter } from "./_components/admin-footer";

// Предрендерим ВСЕ включённые языки. Их список — один файл, который редактирует
// владелец: `config/translations/admin-languages.ts`. Сегодня там два языка,
// целевое состояние продукта — все 82.
//
// Почему у панели не может быть env-набора, как у публичного приложения:
// приложение на :3000 — сайт владельца, и языки там выбирает он под свои рынки;
// панель управления наша, а приходят в неё со всего мира, и мы не знаем страну
// покупателя до входа. Предложить выбрать язык по-английски = потребовать работы
// раньше ценности, то есть потерять человека на самом узком месте воронки.
export function generateStaticParams() {
  return adminLanguages().map((lang) => ({ lang }));
}

// 🔒 `false` — ЖЁСТКАЯ ГАРАНТИЯ СТАТИКИ. Язык, которого нет в списке выше, даёт
// 404 средствами фреймворка: ветка «отрендерить по требованию» ведёт в 404, а не
// в рендер. Значение по умолчанию — `true`, и оно оставляло бы за каждой
// страницей серверную ветку на случай незаявленного языка: страницы всё равно
// оставались бы статическими, но гарантия превращалась бы в обещание.
//
// Флаг остаётся `false` и на 82 языках — расти будет только список включённых
// языков в конфиге. Замер цены роста: одна страница ≈ 72 КБ HTML, 26 × 2 языка =
// 16 МБ; 82 языка дадут ≈ 2 132 страницы и порядка 150 МБ.
export const dynamicParams = false;

// 🔒 ЗАКОН ШАПКИ (2026-08-11, куплен дефектом). Шапка ниже считает ЖИВОЕ
// состояние сервера: область предупреждений (`collectWarnings`), гейт кейсов,
// набор выключенных разделов. У статически предрендеренной страницы этот макет
// исполняется НА СБОРКЕ — то есть до того, как владелец подключил GitHub, домен
// и описал кейсы. Снимок той минуты потом висит в меню месяцами и врёт: владелец
// подключил домен, перешёл на HTTPS и продолжал видеть «нет своего домена».
//
// Поэтому КАЖДАЯ страница под этим макетом обязана нести
// `export const dynamic = "force-dynamic"`. Сюда, в макет, этот флаг не ставится
// намеренно: рядом стоит `generateStaticParams`, и смешивать их в одном файле —
// значит спорить с фреймворком о том, что он предрендерит. Проверка простая:
// новая страница без флага = шапка на ней врёт.

export default async function AdminLangLayout(
  { children, params }: { children: ReactNode; params: Promise<{ lang: string }> },
) {
  const { lang } = await params;
  // Страховка, а не рабочий механизм: при `dynamicParams = false` незаявленный
  // язык до этой строки не доходит — его отсекает фреймворк. Строка стоит здесь
  // на случай, если когда-нибудь флаг переведут в `true`: тогда 404 обязан
  // остаться, а не превратиться в страницу на английском под чужим адресом.
  if (!isAdminLanguage(lang)) notFound();

  const s = getAdminStrings(lang);

  return (
    <div className="flex h-full flex-col bg-background text-foreground">
      {/* Тема ставится ДО первой отрисовки, иначе тёмная панель мигнёт белым на
          каждой загрузке. Скрипт крошечный и синхронный: браузер выполняет его
          при разборе, то есть класс `dark` оказывается на `<html>` раньше, чем
          отрисуется шапка.
          Почему здесь, а не в корневом `app/layout.tsx`: корневой layout общий с
          замороженной старой панелью, и тема прилетела бы и ей — а её на время
          стройки не трогаем. На переключении (Ф3) этот файл станет корневым, и
          скрипт естественно окажется в `<head>`.
          `next/script` со `beforeInteractive` тут не годится: он поддерживается
          только в КОРНЕВОМ layout. */}
      <script
        dangerouslySetInnerHTML={{
          __html:
            "(function(){try{var m=localStorage.getItem('fractera-theme')||'system';" +
            "var d=m==='dark'||(m==='system'&&window.matchMedia('(prefers-color-scheme: dark)').matches);" +
            "document.documentElement.classList.toggle('dark',d);}catch(e){}})();",
        }}
      />

      {/* Выбранная ШИРИНА поднимается тем же приёмом и по той же причине: иначе
          широкая раскладка дёрнется после оживления страницы.
          Второе дело этого скрипта — измерить полосу прокрутки в `--app-sbw`:
          `100vw` включает её, и без поправки широкий режим давал бы
          горизонтальную прокрутку. Пересчитывается на resize и load.
          Перенос с :3000 (`components/app-width-init.tsx`), там `next/script`
          со `beforeInteractive` — здесь он недоступен вне корневого layout. */}
      <script
        dangerouslySetInnerHTML={{
          __html:
            "(function(){var el=document.documentElement;" +
            "try{if(localStorage.getItem('fractera-app-width')==='wide')el.setAttribute('data-app-width','wide');}catch(e){}" +
            "function sbw(){var v=window.innerWidth-el.clientWidth;el.style.setProperty('--app-sbw',(v>0?v:0)+'px');}" +
            "sbw();window.addEventListener('resize',sbw);window.addEventListener('load',sbw);})();",
        }}
      />
      <AdminHeader lang={lang} s={s} />
      {/* Прокручивается содержимое, а не страница: тело документа держит
          h-screen overflow-hidden, поэтому подвал остаётся на месте. */}
      <main className="min-h-0 flex-1 overflow-y-auto">{children}</main>
      <AdminFooter s={s} lang={lang} />
    </div>
  );
}
