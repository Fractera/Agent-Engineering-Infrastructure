import type { ReactNode } from "react";
import { H1, Lead, Eyebrow } from "@/components/ui/typography";

// ШАПКА СТРАНИЦЫ ОБРАЗЦА — ОДИН ПОРЯДОК И ОДИН РИТМ (шаг 28-1, 2026-08-27).
//
// Перенос анатомии с сайта :3000 (`components/content-page/page-header.server.tsx`).
// Там она появилась после замера: шапку собирала каждая страница сама и собирала
// по-своему — пять разных сборок на восемь страниц, подзаголовок в ЧЕТЫРЁХ
// размерах. Разнобой читался как «заголовки разные», хотя кегль H1 к тому
// времени уже совпадал: глаз видит не размер, а расстояние и порядок.
//
// 🔒 ПОРЯДОК ФИКСИРОВАН И НЕ НАСТРАИВАЕТСЯ СНАРУЖИ. Надзаголовок → H1 →
// подзаголовок. Переставить нельзя ничего: возможность переставить — это и есть
// то, из-за чего пять страниц разъехались. Любой элемент можно НЕ ДАТЬ, и тогда
// его просто нет.
//
// 🔒 ПОЧЕМУ НЕ `PageShell`. Общая рамка панели рисует свой заголовок
// `text-base font-semibold` — 16 пикселей, тот самый, который владелец назвал
// отвратительным. Взять её значило бы получить старый заголовок на странице,
// заведённой ради нового. Трогать саму рамку нельзя: она общая на 26 разделов,
// и решение владельца 2026-08-27 — менять только образец.
//
// СЕРВЕРНЫЙ. Ни строчки JS.

export function ExampleHeader({
  eyebrow,
  title,
  subtitle,
  divider = true,
}: {
  /** Короткая метка над заголовком. Нет метки — не передавайте. */
  eyebrow?: string;
  title: string;
  subtitle?: ReactNode;
  /** Черта под шапкой отделяет заголовок от материала. */
  divider?: boolean;
}) {
  return (
    <header className={`flex flex-col gap-4 ${divider ? "border-b border-border pb-8" : ""}`}>
      {eyebrow && <Eyebrow>{eyebrow}</Eyebrow>}

      <H1>{title}</H1>

      {/* Подзаголовок — ВСЕГДА `Lead`. Четыре размера, что были на пяти
          страницах сайта, различались не смыслом, а тем, кто их писал. */}
      {subtitle && <Lead className="max-w-3xl">{subtitle}</Lead>}
    </header>
  );
}
