import type { ReactNode } from "react";

// ВЕРСТАК СЛОЯ «ДИЗАЙН» — две колонки: слева выбор, справа то, что получится.
//
// 🔒 ЗАЧЕМ ОТДЕЛЬНЫЙ ПРИМИТИВ, А НЕ ВЁРСТКА ВНУТРИ СТРАНИЦЫ (заказ владельца
// 2026-08-15). Приём нужен КАЖДОЙ странице этой вкладки: шрифты, шкала, формы,
// цвета — везде одно и то же движение «поменял слева, увидел справа». Повтори мы
// его пять раз руками, получим пять слегка разных верстаков; ровно так в этом
// проекте разъехались пять шапок страниц и пять пустых состояний.
//
// 🔒 ПОЧЕМУ ПРАВАЯ КОЛОНКА ПРИЛИПАЕТ, А НЕ ПРОСТО СТОИТ РЯДОМ. Список выбора
// длиннее экрана — в шрифтах это четырнадцать записей. Без прилипания человек
// прокручивает до нужной строки, нажимает и НЕ ВИДИТ результата: предпросмотр
// остался наверху. Прилипшая колонка держит ответ на глазах всё время, пока
// человек ищет вопрос.
//
// 🔒 НА ТЕЛЕФОНЕ КОЛОНКИ СКЛАДЫВАЮТСЯ, И ПРЕДПРОСМОТР ИДЁТ ПЕРВЫМ. Узкий экран
// не позволяет держать два столбца, а прилипший блок съел бы половину высоты.
// Поэтому там он стоит сверху обычным блоком: человек видит текущее состояние,
// затем прокручивает к выбору.

export function DesignWorkbench({
  controls,
  preview,
}: {
  /** Левая колонка: то, чем управляют. Прокручивается вместе со страницей. */
  controls: ReactNode;
  /** Правая колонка: то, что получится. Держится в поле зрения. */
  preview: ReactNode;
}) {
  return (
    <div className="flex flex-col gap-4 lg:grid lg:grid-cols-[minmax(0,1fr)_minmax(0,22rem)] lg:items-start lg:gap-6">
      {/* Предпросмотр в разметке ПОСЛЕ выбора — так его читает голосовой
          интерфейс и так он ложится на телефоне. Визуальный порядок на широком
          экране задаёт сетка, а не порядок в коде. */}
      <div className="min-w-0 lg:order-1">{controls}</div>

      <div className="lg:order-2 lg:sticky lg:top-4">{preview}</div>
    </div>
  );
}

/** Рамка предпросмотра — общая, чтобы «то, что получится» везде выглядело одинаково. */
export function DesignPreview({ label, children }: { label: string; children: ReactNode }) {
  return (
    <section className="rounded-lg border border-border bg-muted/30 p-3">
      <p className="text-[10px] uppercase tracking-widest text-muted-foreground">{label}</p>
      <div className="mt-2">{children}</div>
    </section>
  );
}
