import { Small } from "@/components/ui/typography";

// ИЛЛЮСТРАЦИЯ ШАГА — ОДИННАДЦАТАЯ СУЩНОСТЬ АНАТОМИИ (шаг 28-14, 2026-08-27).
//
// 🔒 ЗАЧЕМ ОНА. Владелец: «разработать дизайн для изображений, которые должны
// сопровождать шаг; в данный момент я показываю, где брать токен». Шаг второй
// объясняет словами то, что человек ищет ГЛАЗАМИ на чужой странице: где стоит
// «Select scopes», какая галочка первая, как выглядит «No expiration». Снимок
// отвечает на это быстрее любого абзаца — но только если он опознаётся как
// снимок чужого экрана, а не как часть нашей панели.
//
// 🔒 ОТСЮДА ВЕСЬ СТАНДАРТ: РАМКА ГОВОРИТ «ЭТО НЕ ЗДЕСЬ». Снимок ставится в
// рамку с подписью и приглушённой подложкой. Картинка, положенная в интерфейс
// без рамки, читается как продолжение интерфейса: человек ищет на НАШЕЙ странице
// кнопку, которую видел на снимке, и не находит.
//
// 🔒 ПОДПИСЬ ОБЯЗАТЕЛЬНА И ГОВОРИТ, ЧЕЙ ЭТО ЭКРАН. Не «скриншот», а «так это
// выглядит на GitHub»: подпись есть часть объяснения, а не украшение.
//
// 🔒 `alt` — НЕ ПОВТОР ПОДПИСИ. Подпись видят все, `alt` читают вслух тем, кто
// снимка не увидит: он обязан называть СОДЕРЖИМОЕ («отмечена одна галочка repo,
// пять вложенных отметились сами»), иначе для читалки экрана шаг теряет ровно то,
// ради чего снимок поставлен.
//
// 🔒 ОБЫЧНЫЙ `<img>`, А НЕ `next/image`. Снимок лежит в `public/` и отдаётся как
// есть; оптимизатор Next добавил бы к рантайму панели работу, ничего не дав:
// размер уже мал, а адрес известен на сборке. Пропорции задаёт сам файл, поэтому
// `height: auto` — без него на узком экране картинка растянется.

export function StepShot({
  src,
  alt,
  caption,
}: {
  src: string;
  /** Что НА снимке — для тех, кто его не увидит. Не повтор подписи. */
  alt: string;
  /** Подпись под рамкой: чей это экран и на что смотреть. */
  caption: string;
}) {
  return (
    <figure data-step-shot className="mt-6">
      <div className="overflow-hidden rounded-xl border border-border bg-muted/40 p-2">
        <img
          src={src}
          alt={alt}
          loading="lazy"
          decoding="async"
          className="block h-auto w-full rounded-lg"
        />
      </div>
      <figcaption className="mt-2">
        <Small>{caption}</Small>
      </figcaption>
    </figure>
  );
}
