import { ArrowRight } from "lucide-react";

// ССЫЛКА-ДЕЙСТВИЕ ШАГА — ДЕСЯТАЯ СУЩНОСТЬ АНАТОМИИ (шаг 28-11, 2026-08-27).
//
// 🔒 ЭТО НЕ ВТОРОЕ ДЕЙСТВИЕ ШАГА, А ГЛАВНАЯ ЧАСТЬ ЕГО ИНФОРМАЦИИ — решение
// владельца, и оно отменяет моё. Строя шаг 2, я НЕ перенёс ссылку «открыть
// страницу токенов» из живого мастера, рассудив, что она нарушает закон «одно
// действие — один шаг». Владелец рассудил иначе: без ссылки человек не знает,
// КУДА идти делать то единственное действие, ради которого шаг существует.
// Ссылка ведёт наружу, к чужому сервису; действие шага — то, что человек делает
// ЗДЕСЬ, вернувшись оттуда. Это разные вещи, и я их спутал.
//
// 🔒 МЕСТО — НАД ОБЛАСТЬЮ ВВОДА. Дословно: «располагать её надо над областью
// ввода, так как она по сути является главной частью информационной
// составляющей». Под полем её читают после того, как искали значение, которого
// ещё нет; над полем — до того, и это правильный порядок.
//
// 🔒 ФОРМА НАЗВАНА ВЛАДЕЛЬЦЕМ ТОЧНО, И ОТСЕБЯТИНЫ ЗДЕСЬ НЕТ:
//   вид      — «ссылка→ https://…», то есть виден сам адрес, а не только подпись;
//   цвет     — традиционный тёмно-синий (не наш `primary`: ссылка обязана
//              читаться как ссылка, а не как элемент фирменного стиля);
//   движение — мягко влево-вправо на 8 пикселей.
//
// ✗ ЧЕМ ОПЛАЧЕНО. В живом мастере ссылки были и, по словам владельца, «совершенно
// неочевидны»: подпись тем же кеглем, что и текст вокруг, без адреса и без
// движения. Человек их не находил — и не мог сделать шаг, которого от него ждали.
//
// 🔒 ДВИЖЕНИЕ ОСТАНАВЛИВАЕТСЯ ПРИ `prefers-reduced-motion`. У части людей
// постоянное движение на экране вызывает тошноту и мигрень; правило то же, что у
// бегущей ленты на :3000. Ссылка при этом никуда не девается — просто стоит.

export function StepLink({ href, label }: { href: string; label?: string }) {
  return (
    <a
      href={href}
      target="_blank"
      rel="noopener noreferrer"
      data-step-link
      className="launch-link group inline-flex max-w-full items-center gap-2 text-[length:var(--fs-lead)] font-semibold text-[color:var(--link-navy)] underline decoration-[color:var(--link-navy)]/40 underline-offset-4 transition-colors hover:decoration-[color:var(--link-navy)]"
    >
      {/* Слово «ссылка» и стрелка — часть формы, названной владельцем: человек
          опознаёт её как ссылку раньше, чем прочтёт адрес. */}
      <span className="shrink-0 opacity-70">{label ?? "ссылка"}</span>
      <ArrowRight size={16} aria-hidden className="shrink-0" />
      {/* Адрес виден целиком, пока помещается; длинный обрезается — строка не
          имеет права стать двумя, иначе движение читается как дрожание блока. */}
      <span className="truncate">{href}</span>
    </a>
  );
}
