// Общий контракт перетаскивания между колонками раздела меню (шаг 525).
//
// 🔒 ЗАЧЕМ ОТДЕЛЬНЫЙ ТИП ДАННЫХ, А НЕ ОБЩЕЕ СОСТОЯНИЕ. Перетаскиваний здесь ДВА,
// и они разные: внутри правой колонки — ПЕРЕСТАНОВКА уже добавленного пункта,
// слева направо — ДОБАВЛЕНИЕ новой страницы. Отличать их по состоянию компонента
// нельзя: состояние левой колонки правой не видно, а один общий флаг «что-то
// тащат» превращает случайный отпуск мыши в непрошеную правку меню.
//
// Поэтому левая колонка кладёт полезную нагрузку в `dataTransfer` под СВОИМ
// типом. Правая сначала спрашивает: «это моё?» — и только потом решает, что
// делать. Чужое перетаскивание (файл с рабочего стола, текст из другой вкладки)
// в меню не попадёт, потому что под этим типом у него ничего нет.
//
// Тип назван с префиксом приложения намеренно: браузер отдаёт `text/plain` кому
// угодно, и меню начало бы принимать выделенный на странице текст.

/** MIME-тип полезной нагрузки «страница из левой колонки». */
export const DND_ROUTE = "application/x-fractera-route";

/** Что едет в правую колонку: адрес страницы и подпись, предложенная деревом. */
export type DraggedRoute = { href: string; title: string };

/** Прочитать нагрузку, если перетаскивают именно нашу страницу. */
export function readDraggedRoute(dt: DataTransfer): DraggedRoute | null {
  try {
    const raw = dt.getData(DND_ROUTE);
    if (!raw) return null;
    const v = JSON.parse(raw) as Partial<DraggedRoute>;
    return typeof v?.href === "string" && v.href ? { href: v.href, title: String(v.title ?? "") } : null;
  } catch {
    return null;
  }
}

/**
 * Тащат ли НАШУ страницу — вопрос, на который можно ответить ДО отпускания.
 *
 * 🔒 `getData` во время `dragover` возвращает пустую строку: браузер намеренно
 * скрывает содержимое буфера, пока перетаскивание не завершено, — иначе любая
 * страница читала бы то, что человек тащит мимо неё. Поэтому подсветка цели
 * решается по СПИСКУ типов, а не по значению.
 */
export function hasDraggedRoute(dt: DataTransfer): boolean {
  return Array.from(dt.types ?? []).includes(DND_ROUTE);
}
