// `resetFlow()` живёт в `lib/launch-flow.ts` с 28-17 и **не вызывалась ниоткуда**;
// дверь значений при этом отказывает пустой строке, то есть снять сохранённый
// адрес было нечем вовсе. Долг закрыт в тот день, когда владелец сказал: «убери
// все признаки того что я проходил старт через GitHub Clone», — и оказалось, что
// убирать нечем, кроме правки его `.env.local` руками.
//
// 🔒 ПРАВКА РУКАМИ НЕ ГОДИТСЯ НЕ ИЗ ЭСТЕТИКИ. Человек будет проходить путь
// заново — на то он и путь; если каждый повтор требует агента с доступом к
// серверу, способность существует только у нас, а не у него.
//
// 🔒 СБРАСЫВАЕТСЯ ВЕСЬ ПРЕФИКС `USER_FLOW_` ЦЕЛИКОМ, А НЕ ПЕРЕЧЕНЬ КЛЮЧЕЙ.
// Перечень разошёлся бы с состоянием на первом же новом шаге — и разошёлся бы
// молча, оставив на диске то, чего человек уже не видит в пути.
//
// 🔒 `USER_ADOPT_REPO_URL` СТИРАЕТСЯ ОТДЕЛЬНО: он лежит вне префикса и говорит,
// чем в последний раз заменяли слот. После сброса это утверждение неверно.
//
// 🛑 ЧЕГО ЭТА ДВЕРЬ НЕ ДЕЛАЕТ: она НЕ трогает содержимое слота. Состояние пути и
// состояние проекта — разные вещи; вернуть шаблон умеет `launch/adopt` с
// `restore: true`, и смешивать два разрушительных действия в одной двери значило
// бы отнять у человека возможность сделать одно без другого.

export const dynamic = "force-dynamic";

export async function POST(req: NextRequest) {
  if (!(await requireAuth(req.headers.get("cookie") ?? ""))) {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }

  const cleared = resetFlow();

  // Вне префикса, но о том же: чем заменяли слот в последний раз.
  setValue(ADOPT_URL_KEY, null);

  return NextResponse.json({ ok: true, cleared, count: cleared.length });
}
