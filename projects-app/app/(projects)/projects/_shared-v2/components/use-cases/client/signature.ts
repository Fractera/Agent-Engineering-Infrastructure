import type { UseCase } from "../types/use-cases";

// ПОДПИСЬ НАБОРА КЕЙСОВ — детерминированный отпечаток содержимого (id + заголовок + описание каждого
// кейса, по порядку). Ревью-гейт держит в ядре подпись ПОСЛЕДНЕГО подтверждённого набора
// (`useCases.reviewedSignature`); «подтверждено» = подпись текущего набора совпала с ней. Любое
// добавление / удаление / правка меняет содержимое → подпись расходится → гейт снова просит подтвердить
// (правило шага 231, теперь выведенное ИЗ ЯДРА, а не из серверного флага v1). Обе стороны — «подтверждено?»
// и «записать подтверждение» — считают подпись ЭТОЙ функцией, поэтому они всегда сходятся.
export function signatureOf(rows: UseCase[]): string {
  const body = rows.map((r) => `${r.id}␟${r.title}␟${r.summary ?? ""}`).join("␞");
  // FNV-1a 32-бит: детерминированный, зависимостей не тянет, коллизии для нашего объёма пренебрежимы.
  let h = 2166136261;
  for (let i = 0; i < body.length; i++) {
    h ^= body.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return (h >>> 0).toString(36);
}
