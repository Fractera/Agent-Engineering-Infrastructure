// ТИПЫ микросервиса «обрезка изображения» — Кокпит-инструмент мягкого дев/админ-слоя `_shared-v2` (шаг 298).
//
// Инструмент чисто клиентский: берёт исходную картинку (data-URL / object-URL), даёт владельцу выбрать
// кадр и масштаб на canvas и возвращает готовый JPEG-blob. Сервер ему не нужен — расшифровки/загрузки нет,
// blob отдаётся вызывающему коду через колбэк `onDone`, а тот уже решает, куда его положить (объектное
// хранилище склада и т.п.).

/** Соотношение сторон кадра. Ярлыки (16:9 / 1:1 / 9:16) машинные — не переводятся. */
export type CropMode = "horizontal" | "square" | "vertical";

export type ImageCropperProps = {
  /** Открыта ли модалка кадрирования. */
  open: boolean;
  /** Источник картинки (data-URL или object-URL). */
  src: string;
  /** Готовый кадр (JPEG-blob) + выбранное соотношение. */
  onDone: (blob: Blob, cropMode: CropMode) => void;
  /** Отмена / закрытие без результата. */
  onCancel: () => void;
  /** Жёстко закрепить соотношение — тогда переключатель соотношений скрыт. */
  force?: "square" | "horizontal";
  /** Язык интерфейса (правило 4г — десять языков). */
  lang: string;
};
