// ФУНКЦИЯ УЗЛА «OUTPUT-CONNECTOR» — передаёт сообщение узлу ДРУГОЙ автоматизации: дверь наружу в
// групповую. В одиночной автоматизации узел СКРЫТ и не исполняется; доказать его можно только в
// ГРУППЕ автоматизаций (честная граница шага 300 §10 — межавтоматизационную проводку не выдумываем).
// Имя `handToExternal` — публичный контракт, не переименовывать.
//
// Контракт: (ctx) => частичный ctx. Наружу уходит ЦЕЛОЕ сообщение контракта `Message` — сосед получает
// ту же форму, которую говорят все каналы, и его вход-коннектор нормализует её как любой другой канал.
import type { NodeCtx } from "../executor";
import { messageOf } from "../message";

export function handToExternal(ctx: NodeCtx): { handover: unknown } {
  return { handover: messageOf(ctx) };
}
