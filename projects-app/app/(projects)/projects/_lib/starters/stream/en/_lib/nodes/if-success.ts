// ФУНКЦИЯ УЗЛА «CONDITION-SUCCESS» — ветка успеха: пропускает поток к выходам, ТОЛЬКО когда середина
// действительно оставила в контексте непустое сообщение. Возврат `null` — «ветка не держит», штатная
// остановка без ошибки (контракт движка). В типовом прогоне настоящий гейт — бросок в
// `transformPayload`, но условие здесь проверяется по-настоящему, а не рисуется: узел-условие обязан
// решать сам, что бы ни случилось выше. Имя `ifSuccess` — публичный контракт, не переименовывать.
import type { NodeCtx } from "../executor";

export function ifSuccess(ctx: NodeCtx): NodeCtx | null {
  return String(ctx.text ?? "").trim() ? {} : null;
}
