// ФУНКЦИЯ УЗЛА «INTENT» — КЛАСС «САМООПИСАНИЕ» (шаг 311.1, первый узел четвёртого слоя).
//
// ЗАЧЕМ ЭТОТ КЛАСС СУЩЕСТВУЕТ. Часть запросов не требует ни складов, ни внешних инструментов: ответ уже
// лежит в паспорте автоматизации («какая у неё страница?»). В трёхслойной схеме такой маршрут был
// НЕВЫРАЗИМ — закон запрещал ребро «вход → выход», и ответ приходилось протаскивать контрабандой внутрь
// выходного узла. Теперь это законный маршрут `input → intent → output`, минующий середину.
//
// САМ-ГЕЙТ (вариант A закона фронта: узел на класс). Узел сам решает, его ли это запрос:
//   совпало  → возвращает ответ и метку класса, поток идёт дальше в выход;
//   не моё   → `null` = «этот прогон не мой», штатная остановка ветки без ошибки (контракт движка).
// Никакого N-way роутера: каждый класс отвечает только за себя, и добавление класса не трогает соседей.
//
// РАЗБОР ДЕТЕРМИНИРОВАННЫЙ, БЕЗ МОДЕЛИ. Самоописание — вопрос о самой автоматизации, набор его форм
// конечен; ключ/сеть тут не нужны, а значит класс работает на сервере без единого ключа (закон стартера:
// развернул — пользуешься). Модель появится там, где формы запроса действительно бесконечны.
//
// ЧЕСТНЫЙ ИСХОД. Адрес не назначен → так и говорим. Ссылку НЕ ВЫДУМЫВАЕМ никогда (закон паспорта:
// `publicUrl` пуст = «ещё не назначен», и это правда, а не повод сочинить правдоподобный адрес).
//
// ЯЗЫК. Стартер — английский (его дом `_lib/starters/stream/en`); десятиязычие живёт в кокпите
// строителя, а не в рантайм-репликах шаблона.
//
// Имя `intentSelfDescribe` — публичный контракт, не переименовывать.
import type { NodeCtx } from "../executor";
import { readCore } from "../core-io";

// Формы вопроса о самой автоматизации. Список закрытый и короткий: класс отвечает за СЕБЯ, и чужой
// запрос обязан уйти к своему классу, а не быть перехваченным здесь «на всякий случай».
const SELF_QUESTION: RegExp[] = [
  /\bwhat('?s| is)? (the )?(public )?page\b/i,
  /\bwhich page\b/i,
  /\bpage (address|url|link)\b/i,
  /\bwhere (can i |do i |to )?(see|find|view|watch)\b/i,
  /\bwhere is (it|this|the automation)\b/i,
  /\bshow me (the )?(public )?page\b/i,
  /\byour (public )?page\b/i,
];

export async function intentSelfDescribe(ctx: NodeCtx): Promise<NodeCtx | null> {
  const text = String(ctx.text ?? "").trim();
  if (!text) return null; // пустой захват судить нечего — не наш прогон
  if (!SELF_QUESTION.some((re) => re.test(text))) return null; // чужой класс

  const core = await readCore();
  const url = String((core.passport as { publicUrl?: unknown }).publicUrl ?? "").trim();
  const answer = url
    ? `This automation is published at: ${url}`
    : "This automation has no public page address assigned yet — so there is no link to give.";

  return {
    // РЕШЕНИЕ ФРОНТА — часть контекста прогона, а значит и журнала (`runs.jsonl`): маршрут должен быть
    // проверяемым, иначе фронт станет вторым непрозрачным классификатором, о котором никто не знает,
    // почему он так решил.
    intentClass: "self-describe",
    intentRoute: "input → intent → output",
    reply: answer,
    text: answer,
    title: "Self-description",
  };
}
