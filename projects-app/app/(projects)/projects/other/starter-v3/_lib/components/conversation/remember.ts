//
// 🔴 ЗАЧЕМ. Короткая память живёт окном и часом тишины: после паузы вчерашнего разговора не было НИГДЕ, и
// вопрос «помнишь, мы говорили о зелёном велосипеде» было физически не на чем исполнить. Реплики уходили
// в никуда.
//
// 🔒 ПОЧЕМУ ИМЕННО ДВА ДОМА, А НЕ ОДИН ВЕКТОР. Векторная память ОБЩАЯ на весь сервер — в неё пишут все
// автоматизации. По ответу «да, мы это обсуждали» невозможно понять, обсуждали ли это ЗДЕСЬ, а ошибка тут
// самая обидная: уверенная ссылка на чужой разговор. Локальная таблица лежит внутри папки автоматизации,
// поэтому принадлежность в ней соврать не может. Вектор отвечает за СМЫСЛ, таблица — за ПРИНАДЛЕЖНОСТЬ,
// точный текст и ВРЕМЯ (у чанка памяти даты нет вовсе — проверено).
//
// 🔒 МОМЕНТ ЗАПИСИ — ВЫТЕСНЕНИЕ (решение владельца). Реплика уходит в долгую память тогда, когда покидает
// короткую. Это и экономно (ноль сетевых вызовов на каждое «привет»), и осмысленно: пока разговор идёт,
// он и так перед глазами; искать по нему нужно лишь то, что уже забылось.
import { addRow } from "../../rows";
import { rememberFact } from "../../memory";
import { parseConversationTurn } from "../../../_data/record.schema";
import type { ChatMessage } from "./state";

const MARKER = (id: string) => `[mem#${id}]`;

/**
 * Сохранить вытесненные реплики в долгую память. Возвращает, сколько строк записано.
 *
 * Порядок именно такой: сначала СВОЙ id (он же маркер внутри текста документа), потом ингест, потом
 * строка. Так выдержка из памяти всегда разрешается обратно в нашу строку за один шаг — тот же приём,
 * что у `deliverVectorMemory` (308.7).
 *
 * Памяти на сервере нет → строка всё равно пишется: локальная история разговора ценна сама по себе, а
 * терять её из-за отсутствия LightRAG было бы наказанием за чужое отсутствие.
 */
export async function rememberConversation(
  dropped: ChatMessage[],
  meta: { channel: string; chatKey: string },
): Promise<number> {
  let saved = 0;
  for (const m of dropped) {
    const text = String(m.text ?? "").trim();
    if (!text) continue;
    const id = `cnv${Date.now().toString(36)}${Math.random().toString(36).slice(2, 8)}`;
    let trackId: string | null = null;
    try {
      // Маркер — В ТЕКСТЕ документа: ответ памяти, процитировавший его, разрешается в эту строку.
      trackId = await rememberFact(`${MARKER(id)} ${text}`, meta.channel, undefined, "conversation");
    } catch {
      trackId = null; // память отказала — прогон из-за этого не падает, реплика всё равно ляжет локально
    }
    const row = {
      text,
      role: m.role,
      channel: meta.channel,
      chatKey: meta.chatKey,
      at: m.at,
      ...(m.runId ? { runId: m.runId } : {}),
      ...(trackId ? { trackId } : {}),
      memRecordId: id,
    };
    parseConversationTurn(row);
    await addRow("conversation", row, id);
    saved++;
  }
  return saved;
}
