// СБОРЩИК КОНТЕКСТА ДИАЛОГА (шаг 330.2) — ЕДИНСТВЕННОЕ место, где решается, что именно уезжает модели.
//
// 🔴 ЗАЧЕМ. До этого ограничителем было ЧИСЛО РЕПЛИК, и оно плохо меряет цену: десять слов и десять
// расшифровок голоса стоят по-разному в сто раз. Один длинный диктофонный кусок съедал контекст целиком,
// и никто этого не видел — ни владелец, ни журнал. Обратная беда так же реальна: механически уменьшить
// окно значит сделать ассистента забывчивым. Правильная мера — БЮДЖЕТ В ТОКЕНАХ с приоритетом и
// вытеснением: сколько поместилось — столько и едет, а что не поместилось, названо вслух.
//
// 🔒 ДВА ОГРАНИЧИТЕЛЯ, ОБА ЧЕСТНЫЕ. Окно (`lastN`) — «сколько реплик вообще имеет смысл помнить», бюджет
// (`tokenBudget`) — «сколько мы готовы за это платить». Срабатывает тот, который упирается раньше, и
// `limitedBy` говорит, какой именно. Прятать это нельзя: владелец обязан понимать, почему ассистент не
// помнит начало разговора — потому что реплик много или потому что они длинные.
//
// 🔒 ВЫТЕСНЕНИЕ СНИЗУ, А НЕ ОБРЕЗКА ПОПОЛАМ. Выбрасывается САМОЕ СТАРОЕ целыми репликами: половина фразы
// в контексте хуже её отсутствия — модель достраивает обрезанное и уверенно врёт. Свежее сообщение не
// выбрасывается никогда, даже если одно оно больше бюджета: разговор без последней реплики бессмыслен.
//
// Формат строк здесь НЕ живёт — он один на всю папку (`formatDialog`, закон 330.1). Этот модуль решает
// СКОЛЬКО, а не КАК.
import { formatDialog, type ChatMessage } from "./state";

/**
 * ОЦЕНКА ЦЕНЫ ТЕКСТА В ТОКЕНАХ — детерминированная, без токенизатора (закон 0: внутри папки только zod и
 * встроенное в node). Латиница ≈ 4 знака на токен, всё остальное (кириллица, греческий, CJK, эмодзи) ≈ 2:
 * так оценка не врёт в опасную сторону на русском разговоре. Это оценка СВЕРХУ-ПРИБЛИЗИТЕЛЬНО, и её
 * задача — держать порядок величины, а не совпасть с биллингом провайдера.
 */
export function estimateTokens(text: string): number {
  let ascii = 0;
  let wide = 0;
  for (const ch of text) {
    if ((ch.codePointAt(0) ?? 0) < 128) ascii++;
    else wide++;
  }
  return Math.ceil(ascii / 4 + wide / 2);
}

export type DialogueContext = {
  /** Готовый текст: сводка сессии (если есть) + история в общей форме (`formatDialog`). */
  text: string;
  /** Сколько стоила сводка сессии. Ноль — её не было. */
  summaryUsed: number;
  /** Сколько токенов он стоит по нашей оценке. */
  used: number;
  /** Бюджет, с которым собирали. */
  budget: number;
  /** Сколько реплик не поместилось (самые старые). */
  dropped: number;
  /** Что упёрлось первым: окно владельца, бюджет или ничего (влезло всё). */
  limitedBy: "window" | "budget" | "none";
  /** Удержана ли ЗАВЯЗКА разговора — первая реплика окна (см. закон закрепления ниже). */
  openingKept: boolean;
};

/**
 * 🔒 ЗАВЯЗКА РАЗГОВОРА ЗАКРЕПЛЯЕТСЯ (шаг 332.B, дефект доказан набором проверок 2026-08-04).
 *
 * Вытеснение шло строго снизу — значит первой уезжала ПЕРВАЯ реплика, а она называет предмет разговора.
 * Живой замер: «свадьба сестры в <городе>» → три реплики болтовни → «в каком городе свадьба?» → «не вижу,
 * у меня тут только про музыку». Предмет потерян, хотя человек его назвал.
 *
 * Сводка сессии здесь НЕ помогает и это важно понимать: она собирается при вытеснении из БУФЕРА
 * (`pushMessage`), а тут реплики из буфера не уходили — они просто не влезли в бюджет ПРИ ЧТЕНИИ. То есть
 * у бюджетного вытеснения не было никакого уплотнения вообще.
 *
 * Поэтому первая реплика окна получает бронь — тот же приём, что защищает последнюю, и та же логика, что
 * у зрелых оркестраторов (в Hermes это `protect_first_human`). Две оговорки, обе обязательные:
 *   1. бронь ограничена долей бюджета — гигантская первая реплика не имеет права вытеснить настоящее;
 *   2. если между закреплённой завязкой и остатком что-то выброшено, разрыв НАЗЫВАЕТСЯ вслух: иначе
 *      модель читает две далёкие реплики как соседние и уверенно врёт про порядок событий.
 */
const OPENING_SHARE = 0.25;
const OPENING_GAP = "[…earlier turns omitted…]";
/**
 * 🔒 «ПРИВЕТ» — НЕ ЗАВЯЗКА (поймано замером сразу после первой версии закрепления). Первой репликой сессии
 * очень часто оказывается приветствие или короткое «ок»: закрепив его, мы платим бюджетом за реплику,
 * которая ничего не называет, и ЗАМЕЩАЕМ ею настоящий предмет разговора. Поэтому якорем берётся первая
 * реплика ЧЕЛОВЕКА, которая что-то говорит: не короче этого порога и не дороже доли бюджета.
 *
 * Почему именно человека: ответы бота несут вердикт прошлого прогона, и закреплять их — тот же дефект
 * заражения, что уже пойман у классификатора (`userTurnsOnly`).
 *
 * Порог считается по ТЕКСТУ реплики, а не по её готовой строке: метка времени и роль добавляют около
 * восьми токенов каждой строке, поэтому «hello» по строке выглядит содержательным — на этом первая версия
 * порога и промахнулась, закрепив приветствие вместо предмета разговора.
 */
const OPENING_MIN = 6;

/**
 * СОБРАТЬ ИСТОРИЮ ПОД БЮДЖЕТ. Порядок ровно такой:
 *   1. окно владельца (`lastN`) отсекает хвост по числу реплик — это его решение «что вообще помнить»;
 *   2. бюджет отсекает старое по цене, пока не влезет;
 *   3. последняя реплика остаётся всегда.
 */
export function buildDialogue(
  messages: ChatMessage[],
  opts: { lastN: number; tokenBudget: number; summary?: string; ttlMinutes?: number },
): DialogueContext {
  const budget = Math.max(1, Math.trunc(opts.tokenBudget));
  const windowN = Math.max(1, Math.trunc(opts.lastN));

  // 🔒 СРОК ДЕЙСТВУЕТ И ПРИ ЧТЕНИИ (330.4R, дефект пойман замером «переживает ли просьба паузу»).
  // TTL применялся только при ЗАПИСИ (`trim` внутри `pushMessage`), а движок отдавал буфер модели как
  // есть — до того, как запись случится. Поэтому после паузы протухшие реплики уезжали в модель ЕЩЁ ОДИН
  // раз, и «час тишины = чистая сессия» было неправдой ровно на один прогон. Срок обязан значить одно и
  // то же с обеих сторон.
  const ttl = Math.trunc(opts.ttlMinutes ?? 0);
  if (ttl > 0) {
    const cutoff = Date.now() - ttl * 60_000;
    messages = messages.filter((m) => {
      const t = new Date(m.at).getTime();
      return Number.isFinite(t) ? t >= cutoff : true;
    });
  }

  // 🔒 СВОДКА СЕССИИ РЕЗЕРВИРУЕТСЯ, А НЕ КОНКУРИРУЕТ (330.4). Первоначальный набросок ставил её последней
  // в очереди на вытеснение — и это оказалось неверно: сводка стоит около сотни токенов, а покрывает ВЕСЬ
  // вытесненный разговор. Выбросить её ради двух лишних дословных реплик значит обменять память сессии на
  // мелочь. Поэтому её цена снимается с бюджета ПЕРВОЙ, а конкурируют за остаток уже реплики.
  //
  // Ярлык обязателен: без пометки «это уплотнённое прошлое» модель читает сводку как только что сказанное
  // и путает времена — самый уверенный род галлюцинаций.
  const summaryText = String(opts.summary ?? "").trim();
  const summaryBlock = summaryText ? `[earlier in this session, condensed] ${summaryText}` : "";
  const summaryUsed = summaryBlock ? estimateTokens(summaryBlock) : 0;
  const rest = Math.max(1, budget - summaryUsed);

  const join = (history: string) => [summaryBlock, history].filter(Boolean).join("\n");

  if (!messages.length) {
    return { text: join(""), summaryUsed, used: summaryUsed, budget, dropped: 0, limitedBy: "none", openingKept: false };
  }

  const windowed = messages.slice(-windowN);
  const droppedByWindow = messages.length - windowed.length;

  // Цена реплики считается по её ГОТОВОЙ строке, а не по голому тексту: метка времени и роль тоже едут
  // в модель и тоже стоят денег. Считать иначе значит обманывать себя на четверть контекста.
  const priced = windowed.map((m) => ({ m, cost: estimateTokens(formatDialog([m], 1)) }));

  // Завязка бронируется ДО торга за бюджет — иначе её судьба решалась бы порядком, а не важностью.
  // Условия брони: разговор длиннее двух реплик (в короткой беседе завязка и так на месте) и сама она
  // умещается в отведённую долю.
  const openingCap = Math.max(1, Math.floor(rest * OPENING_SHARE));
  const openingAt = priced.length >= 3
    ? priced.findIndex((p) => p.m.role === "user" && estimateTokens(p.m.text) >= OPENING_MIN && p.cost <= openingCap)
    : -1;
  const opening = openingAt >= 0 ? priced[openingAt] : null;
  const pool = opening ? priced.filter((_, i) => i !== openingAt) : priced;

  let kept = pool;
  let total = priced.reduce((s, p) => s + p.cost, 0);
  while (kept.length > 1 && total > rest) {
    total -= kept[0].cost;
    kept = kept.slice(1);
  }
  const droppedByBudget = pool.length - kept.length;

  // Разрыв называется вслух ровно тогда, когда он есть: закреплённая завязка + выброшенная середина.
  const body = opening && droppedByBudget > 0
    ? [formatDialog([opening.m], 1), OPENING_GAP, formatDialog(kept.map((p) => p.m), kept.length)].join("\n")
    : formatDialog((opening ? [opening, ...kept] : kept).map((p) => p.m), kept.length + (opening ? 1 : 0));

  const text = join(body);
  return {
    text,
    summaryUsed,
    used: estimateTokens(text),
    budget,
    dropped: droppedByWindow + droppedByBudget,
    limitedBy: droppedByBudget > 0 ? "budget" : droppedByWindow > 0 ? "window" : "none",
    openingKept: Boolean(opening),
  };
}

/**
 * 🔒 СЖАТИЕ ВЫТЕСНЕННОГО БЕЗ МОДЕЛИ — ФОЛБЭК, КОТОРЫЙ НЕ ВРЁТ (330.4).
 *
 * Нет ключа или модель недоступна — сводка всё равно обязана появиться, иначе вытесненное пропадёт
 * совсем. Но выдумывать «смысл» детерминированный код не вправе, поэтому он честно перечисляет НАЧАЛА
 * реплик: это не пересказ, а оглавление, и модель прочтёт его именно так.
 */
export function outlineOf(dropped: ChatMessage[], limit: number): string {
  const head = (s: string) => {
    const one = s.replace(/\s+/g, " ").trim();
    return one.length <= 60 ? one : `${one.slice(0, 59)}…`;
  };
  const parts = dropped.map((m) => `${m.role === "user" ? "they" : "we"}: ${head(m.text)}`);
  let out = parts.join(" · ");
  if (out.length > limit) out = `${out.slice(0, limit - 1)}…`;
  return out;
}

/**
 * 🔒 ДОЛЯ КЛАССИФИКАТОРА — ВЫВОДИТСЯ, А НЕ НАСТРАИВАЕТСЯ (330.2).
 *
 * Чтение класса запроса тоже нуждается в контексте: короткое «а второе?» без предыдущих реплик не
 * опознаётся ничем. Но ему нужна ЗАВЯЗКА разговора, а не весь разговор: класс решается по последнему
 * обмену, и лишние реплики только удорожают вызов, который случается на КАЖДОМ прогоне.
 *
 * Второй настройкой это быть не может: владелец не обязан знать, что внутри два потребителя контекста, а
 * две ручки с непонятной разницей — способ получить противоречивую конфигурацию. Поэтому доля выводится
 * из единственного бюджета и зажата разумными краями.
 */
export const classifyBudget = (tokenBudget: number): number =>
  Math.min(400, Math.max(60, Math.round(Math.max(1, tokenBudget) * 0.25)));

/** Окно классификатора — тоже производное: последний обмен, не вся сессия. */
export const classifyWindow = (lastN: number): number => Math.min(6, Math.max(2, Math.trunc(lastN)));

/**
 * 🔒 КЛАССИФИКАТОРУ — ТОЛЬКО РЕПЛИКИ ЧЕЛОВЕКА (330.2R, регресс пойман живьём 2026-08-03).
 *
 * Дав чтению класса весь диалог, я дал ему ЗАРАЖАТЬСЯ. Живой прогон: бот однажды ответил «не могу понять,
 * это вопрос или запись» — и следующее «привет, как дела?» тоже стало `unclaimed`, хотя в чистом чате та
 * же фраза уверенно опознаётся как `small-talk`. Модель видела вердикт прошлого прогона и повторяла его:
 * отказ в истории работал как инструкция отказывать дальше. Разговор залипал в «я не умею».
 *
 * Реплики ЧЕЛОВЕКА такого эффекта не дают: в них нет вердикта, только предмет разговора — ровно то, ради
 * чего контекст и нужен («а второе?» разрешается предыдущим вопросом человека, а не ответом бота).
 */
export const userTurnsOnly = (messages: ChatMessage[]): ChatMessage[] => messages.filter((m) => m.role === "user");

/**
 * 🔒 КОНТЕКСТ КЛАССИФИКАТОРУ — ТОЛЬКО КОГДА СООБЩЕНИЕ НЕПОЛНО (330.2R).
 *
 * Полная фраза опознаётся сама и в контексте не нуждается — а лишний контекст ей только вредит (см. выше).
 * Неполной же реплику делает ССЫЛКА НА СКАЗАННОЕ РАНЬШЕ: короткий ответ («да», «второе», «завтра») либо
 * висящий вопрос, на который она отвечает. Оба признака объективны, поэтому решаем детерминированно, не
 * спрашивая модель.
 */
export const needsContextToClassify = (text: string, hasPending: boolean): boolean => {
  if (hasPending) return true; // висит вопрос — следующая реплика по определению его продолжение
  const words = text.trim().split(/\s+/).filter(Boolean);
  return words.length <= 3; // «второе», «да, давай», «завтра в шесть» — сами по себе не значат ничего
};
