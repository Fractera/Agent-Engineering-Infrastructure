import type { Automation } from "../../_data/automation.schema";

export type Task = {
  /** cuid кейса — он же уезжает в прогон как `taskCase`. */
  cuid: string;
  number: number;
  /** Короткое имя для кнопки. */
  title: string;
  /** Полный текст кейса — показывается под кнопкой, когда задача выбрана. */
  text: string;
};

/**
 * Задачи автоматизации. Кейсы в статусе `in-development` включаются: узлы под них уже раскрыты, и
 * человек вправе их запускать — это и есть наш собственный `lifecycle: real-project`. Замороженный
 * шаблон кейсов не имеет вовсе, поэтому список у него пуст, и кнопок не будет.
 */
export function tasksOf(core: Automation): Task[] {
  const cases = Array.isArray(core.useCases?.cases) ? core.useCases.cases : [];
  return cases
    .map((c) => ({ cuid: c.cuid, number: c.number, title: String(c.title ?? "").trim(), text: String(c.text ?? "").trim() }))
    .filter((t) => t.title);
}
