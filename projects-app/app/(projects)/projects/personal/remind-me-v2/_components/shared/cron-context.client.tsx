"use client";

import { createContext, useContext, type ReactNode } from "react";
import type { CronSettings } from "./schedule";

// ПРОВАЙДЕР ТАКТА — ОБЩИЙ СИГНАЛ АВТОМАТИЗАЦИИ (шаг 298, вопрос владельца: «а другим компонентам тоже
// понадобится крон?»). Да, понадобится — и поэтому такт раздаётся ПРОВАЙДЕРОМ, а не пропом.
//
// ПОЧЕМУ. У крона две природы. Как ВКЛАДКА он такой же продуктовый раздел, как календарь (своя папка,
// своя заявка ИИ). Но его ТАКТ — не свойство вкладки, а факт всей автоматизации: сегодня его читают
// календарь (сторож наступления) и верхняя полоса-пульс, завтра — хранилище, дайджест уведомлений, любая
// новая вкладка. Прокидывать его пропом означало бы тянуть цепочку через каждый уровень (так и было:
// `index` → `calendar` → `loader` → `due-watch`) и расширять сигнатуры при КАЖДОМ новом потребителе.
//
// КАК УСТРОЕНО. Композиция страницы читает такт ОДИН раз из ядра (`cronOf`, единственный читатель) и
// кладёт сюда. Любой клиентский компонент берёт его хуком `useCron()` — ни одного лишнего пропа. Крон
// выключен или раздела нет — `null`, и потребитель сам решает, что показывать.
//
// Провайдер живёт в ПАПКЕ (`_components/shared/`), а не в дев-слое: такт нужен РАНТАЙМУ (сторож
// наступления работает у конечного пользователя), а всё, что нужно рантайму, живёт внутри папки.
const CronContext = createContext<CronSettings | null>(null);

export function CronProvider({ cron, children }: { cron: CronSettings | null; children: ReactNode }) {
  return <CronContext.Provider value={cron}>{children}</CronContext.Provider>;
}

/** Такт расписания этой автоматизации: `{enabled, everyMinutes}` или `null`, если крона нет/выключен. */
export function useCron(): CronSettings | null {
  return useContext(CronContext);
}
